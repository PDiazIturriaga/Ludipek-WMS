from enum import StrEnum

class EstadoWms(StrEnum):
    PENDIENTE_PICKING = "PENDIENTE_PICKING"
    PICKING_EN_PROCESO = "PICKING_EN_PROCESO"
    PICKING_COMPLETO = "PICKING_COMPLETO"
    PENDIENTE_PACKING = "PENDIENTE_PACKING"
    PACKING_EN_PROCESO = "PACKING_EN_PROCESO"
    PACKING_COMPLETO = "PACKING_COMPLETO"
    EN_TRANSITO_CCP = "EN_TRANSITO_CCP"
    RECEPCION_CCP_EN_PROCESO = "RECEPCION_CCP_EN_PROCESO"
    RECIBIDO_CCP = "RECIBIDO_CCP"
    RECIBIDO_CCP_CON_DIFERENCIAS = "RECIBIDO_CCP_CON_DIFERENCIAS"
    FACTURADA = "FACTURADA"

class EstadoNetSuite(StrEnum):
    PENDIENTE_FACTURACION = "PENDIENTE_FACTURACION"
    FACTURADO = "FACTURADO"
    ERROR_FACTURACION = "ERROR_FACTURACION"
    NO_APLICA = "NO_APLICA"

class EstadoRecepcion(StrEnum):
    PENDIENTE_RECEPCION = "PENDIENTE_RECEPCION"
    RECEPCION_EN_PROCESO = "RECEPCION_EN_PROCESO"
    RECIBIDO_CONFORME = "RECIBIDO_CONFORME"
    RECIBIDO_CON_DIFERENCIAS = "RECIBIDO_CON_DIFERENCIAS"
    PENDIENTE_QA = "PENDIENTE_QA"
    QA_APROBADO = "QA_APROBADO"
    QA_RECHAZADO = "QA_RECHAZADO"
    PENDIENTE_PUTAWAY = "PENDIENTE_PUTAWAY"
    UBICADO = "UBICADO"
    CUARENTENA = "CUARENTENA"
    CERRADO = "CERRADO"

TRANSICIONES_WMS = {
    EstadoWms.PENDIENTE_PICKING: {EstadoWms.PICKING_EN_PROCESO},
    EstadoWms.PICKING_EN_PROCESO: {EstadoWms.PICKING_COMPLETO},
    EstadoWms.PICKING_COMPLETO: {EstadoWms.PENDIENTE_PACKING},
    EstadoWms.PENDIENTE_PACKING: {EstadoWms.PACKING_EN_PROCESO},
    EstadoWms.PACKING_EN_PROCESO: {EstadoWms.PACKING_COMPLETO, EstadoWms.EN_TRANSITO_CCP},
    EstadoWms.EN_TRANSITO_CCP: {EstadoWms.RECEPCION_CCP_EN_PROCESO},
    EstadoWms.RECEPCION_CCP_EN_PROCESO: {
        EstadoWms.RECIBIDO_CCP,
        EstadoWms.RECIBIDO_CCP_CON_DIFERENCIAS,
    },
}

def validar_transicion(actual: str, nuevo: str) -> bool:
    try:
        return EstadoWms(nuevo) in TRANSICIONES_WMS.get(EstadoWms(actual), set())
    except ValueError:
        return False
