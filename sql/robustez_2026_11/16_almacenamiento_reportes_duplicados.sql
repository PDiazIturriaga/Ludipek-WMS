-- 1) Ubicaciones escritas sin guiones se corrigen solas: B2501 / B25-01 / B-2501 -> B-25-01,
--    BE0312 -> BE-03-12.
-- 2) Historial del operador en Almacenamiento (lo que guardó en las últimas horas)
--    y reportes desde el celular ("reportar un problema") que el PC ve en alertas.
-- 3) Eliminar filas de stock duplicadas (misma ubicación, SKU, lote, vencimiento y
--    cantidad). Solo los usuarios de wms_config.usuarios_depuran_stock (por defecto: Beto).
-- Después de este script vuelva a ejecutar el 14 (agrega la alerta de reportes).
-- =====================================================================
begin;

-- ---------------------------------------------------------------------
-- 1) Normalizar ubicaciones (también formatos compactos)
-- ---------------------------------------------------------------------
create or replace function public.wms_normalizar_ubicacion(p text)
returns text language sql immutable as $$
  with b as (
    select regexp_replace(
             regexp_replace(
               regexp_replace(upper(btrim(coalesce(p, ''))), '^RACK\s*', ''),
               '\s+', '-', 'g'),
             '-+', '-', 'g') s
  )
  select case
           when s ~ '^[A-Z]-?[0-9]{2}-?[0-9]{2}$'
             then substr(replace(s, '-', ''), 1, 1) || '-' || substr(replace(s, '-', ''), 2, 2) || '-' || substr(replace(s, '-', ''), 4, 2)
           when s ~ '^(MK|ME|BE)-?[0-9]{2}-?[0-9]{2}$'
             then substr(replace(s, '-', ''), 1, 2) || '-' || substr(replace(s, '-', ''), 3, 2) || '-' || substr(replace(s, '-', ''), 5, 2)
           else s
         end
  from b;
$$;

-- ---------------------------------------------------------------------
-- 2a) Historial del operador (Almacenamiento y envío a merma)
-- ---------------------------------------------------------------------
create or replace function public.wms_mis_almacenamientos(p_bodega text, p_usuario text, p_horas integer default 24)
returns table (lpn text, destino text, ubicacion_actual text, tipo text, skus integer, unidades integer, fecha timestamptz, detalle text)
language sql stable security definer set search_path = public as $$
  with k as (
    select h.lpn, h.ubicacion_destino destino, h.tipo_movimiento tipo, h.sku, h.unidades_afectadas un,
           date_trunc('minute', h.fecha) minuto, h.fecha
    from historial_movimientos h
    where h.bodega = public.wms_bodega_valida(p_bodega)
      and h.tipo_movimiento in ('ALMACENAMIENTO', 'ENVIO_MERMA')
      and upper(coalesce(h.usuario, '')) = upper(btrim(coalesce(p_usuario, '')))
      and h.fecha > now() - make_interval(hours => greatest(coalesce(p_horas, 24), 1))
      and coalesce(h.lpn, '') <> ''
  )
  select k.lpn, k.destino,
         coalesce(
           (select string_agg(distinct i.codigo_ubicacion, ', ')
              from bodega_inventario_ubicacion i
             where i.bodega = public.wms_bodega_valida(p_bodega) and i.lpn = k.lpn and i.cantidad_unidades > 0
               and not public.wms_es_ubicacion_picking(i.codigo_ubicacion) and i.codigo_ubicacion <> 'ZONA-PICKING'),
           (select string_agg(distinct i.codigo_ubicacion, ', ')
              from bodega_inventario_ubicacion i
             where i.bodega = public.wms_bodega_valida(p_bodega) and i.lpn = k.lpn and i.cantidad_unidades > 0)),
         min(k.tipo), count(distinct k.sku)::int, sum(k.un)::int, max(k.fecha),
         string_agg(k.sku || ' · ' || k.un || ' UN', ' | ' order by k.sku)
  from k
  group by k.lpn, k.destino, k.minuto
  order by max(k.fecha) desc
  limit 60;
$$;

-- ---------------------------------------------------------------------
-- 2b) Reportes de los operadores
-- ---------------------------------------------------------------------
create table if not exists public.wms_reportes_operacion (
  id           bigint generated by default as identity primary key,
  bodega       text not null,
  modulo       text not null default 'ALMACENAMIENTO',
  tipo         text not null,
  lpn          text,
  ubicacion    text,
  sku          text,
  detalle      text,
  usuario      text not null,
  creado_en    timestamptz not null default now(),
  estado       text not null default 'ABIERTO' check (estado in ('ABIERTO', 'RESUELTO')),
  resuelto_por text,
  resuelto_en  timestamptz,
  nota         text
);
alter table public.wms_reportes_operacion enable row level security;
create index if not exists idx_reportes_operacion_abiertos on public.wms_reportes_operacion (bodega, estado, creado_en desc);

create or replace function public.wms_crear_reporte_operacion(
  p_bodega text, p_modulo text, p_tipo text, p_lpn text, p_ubicacion text, p_sku text, p_detalle text, p_usuario text)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_id bigint;
begin
  if nullif(btrim(coalesce(p_tipo, '')), '') is null then raise exception 'WMS: indique qué pasó'; end if;
  if nullif(btrim(coalesce(p_usuario, '')), '') is null then raise exception 'WMS: falta el usuario'; end if;
  insert into wms_reportes_operacion (bodega, modulo, tipo, lpn, ubicacion, sku, detalle, usuario)
  values (public.wms_bodega_valida(p_bodega), upper(coalesce(nullif(btrim(p_modulo), ''), 'ALMACENAMIENTO')),
          btrim(p_tipo), nullif(upper(btrim(coalesce(p_lpn, ''))), ''),
          nullif(public.wms_normalizar_ubicacion(p_ubicacion), ''), nullif(upper(btrim(coalesce(p_sku, ''))), ''),
          nullif(btrim(coalesce(p_detalle, '')), ''), upper(btrim(p_usuario)))
  returning id into v_id;
  return v_id;
end $$;

-- ---------------------------------------------------------------------
-- 3) Depurar stock duplicado (solo usuarios autorizados)
-- ---------------------------------------------------------------------
insert into public.wms_config (clave, valor, descripcion)
select 'usuarios_depuran_stock',
       coalesce((select string_agg(upper(usuario), ',') from public.wms_usuarios
                  where usuario ilike 'beto%' or nombre_completo ilike 'alberto hern%'), 'BETO'),
       'Usuarios (separados por coma) que pueden eliminar stock duplicado desde el celular'
on conflict (clave) do nothing;

create or replace function public.wms_puede_depurar_stock(p_usuario text)
returns boolean language sql stable security definer set search_path = public as $$
  select upper(btrim(coalesce(p_usuario, ''))) = any (
           string_to_array(replace(upper(coalesce((select valor from wms_config where clave = 'usuarios_depuran_stock'), '')), ' ', ''), ','))
         and upper(btrim(coalesce(p_usuario, ''))) <> '';
$$;

create or replace function public.wms_eliminar_stock_duplicado(p_inventario_id bigint, p_usuario text, p_motivo text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_usuario text := public.wms_contexto(p_usuario, 'wms_eliminar_stock_duplicado');
  o record;
  v_gemelo bigint;
begin
  if not public.wms_puede_depurar_stock(p_usuario) then
    raise exception 'WMS: su usuario no está autorizado para eliminar stock duplicado';
  end if;
  select * into o from bodega_inventario_ubicacion where id = p_inventario_id for update;
  if not found then raise exception 'WMS: esa fila de stock ya no existe (actualice la consulta)'; end if;
  select i.id into v_gemelo
  from bodega_inventario_ubicacion i
  where i.id <> o.id and i.bodega = o.bodega and i.codigo_ubicacion = o.codigo_ubicacion and i.sku = o.sku
    and coalesce(i.lote, 'S/L') = coalesce(o.lote, 'S/L')
    and coalesce(i.fecha_vencimiento_cl, '') = coalesce(o.fecha_vencimiento_cl, '')
    and i.cantidad_unidades = o.cantidad_unidades
  order by i.id
  limit 1;
  if v_gemelo is null then
    raise exception 'WMS: no hay otra fila igual en % (mismo SKU, lote, vencimiento y cantidad). Si el stock está mal, corríjalo con conteo cíclico.', o.codigo_ubicacion;
  end if;
  delete from bodega_inventario_ubicacion where id = o.id;
  perform public.wms_kardex(o.bodega, 'ELIMINAR_DUPLICADO', o.lpn, o.sku, o.lote, o.codigo_ubicacion,
                            left('DUPLICADO DE ID ' || v_gemelo || coalesce(' · ' || nullif(btrim(p_motivo), ''), ''), 120),
                            coalesce(o.cajas, 0), o.cantidad_unidades);
  return jsonb_build_object('eliminado', o.id, 'se_conserva', v_gemelo, 'ubicacion', o.codigo_ubicacion,
                            'sku', o.sku, 'lpn', o.lpn, 'unidades', o.cantidad_unidades);
end $$;

grant execute on function public.wms_normalizar_ubicacion(text) to anon, authenticated, service_role;
grant execute on function public.wms_mis_almacenamientos(text, text, integer) to anon, authenticated, service_role;
grant execute on function public.wms_crear_reporte_operacion(text, text, text, text, text, text, text, text) to anon, authenticated, service_role;
grant execute on function public.wms_puede_depurar_stock(text) to anon, authenticated, service_role;
grant execute on function public.wms_eliminar_stock_duplicado(bigint, text, text) to anon, authenticated, service_role;

commit;

