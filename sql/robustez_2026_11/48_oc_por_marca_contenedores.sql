--
-- 1) La copia de NetSuite marca qué OC siguen abiertas (pendientes de recepción, parciales o por
--    aprobar), sin importar cuándo se crearon: hay OC que llegan 4 a 6 meses después.
-- 2) Packing list por contenedor (wms_pl_contenedores): una OC puede traer varios contenedores y cada
--    uno con su PL. El PC lo guarda al cargar el PL; la nota del documento también se guarda.
-- 3) Vistas para el PC: marcas con OC abiertas → OC de la marca → contenedores de la OC con su
--    estado (PL cargado, agendado, en recepción, recibido) → detalle del contenedor (PL vs recibido).
-- 4) El celular lista los contenedores de la OC para elegir cuál está recibiendo.
-- Se puede ejecutar más de una vez.
-- =====================================================================
