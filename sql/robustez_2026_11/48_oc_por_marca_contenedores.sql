grant select, insert, update, delete on public.wms_pl_contenedores, public.wms_pl_contenedor_detalle to service_role;

create or replace function public.wms_contenedor_normal(p text)
returns text language sql immutable as $$
  select nullif(upper(regexp_replace(btrim(coalesce(p, '')), '[\s\-]+', '', 'g')), '');
$$;

-- Guarda (o reemplaza) el PL de un contenedor. p_lineas: [{sku, descripcion, lote, vencimiento, cajas, multiplo, unidades}]
create or replace function public.wms_pl_guardar(p_numero_oc text, p_contenedor text, p_lineas jsonb,
                                                 p_referencia text default null, p_proveedor text default null,
                                                 p_asn_id bigint default null, p_nota text default null,
                                                 p_archivo text default null, p_usuario text default null,
                                                 p_eta date default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_oc text := public.wms_numero_oc(p_numero_oc);
  v_cont text := public.wms_contenedor_normal(p_contenedor);
  v_id bigint;
begin
  if v_oc is null then raise exception 'WMS: falta el número de OC del packing list'; end if;
  if v_cont is null then raise exception 'WMS: falta el número de contenedor del packing list'; end if;
  insert into wms_pl_contenedores as p (numero_oc, contenedor, referencia_pl, proveedor, asn_id, nota, archivo, creado_por, eta)
  values (v_oc, v_cont, nullif(btrim(p_referencia), ''), nullif(btrim(p_proveedor), ''), p_asn_id,
          nullif(btrim(p_nota), ''), p_archivo, p_usuario, p_eta)
  on conflict (numero_oc, contenedor) do update
    set referencia_pl = coalesce(excluded.referencia_pl, p.referencia_pl),
        proveedor = coalesce(excluded.proveedor, p.proveedor),
        asn_id = coalesce(excluded.asn_id, p.asn_id),
        nota = coalesce(excluded.nota, p.nota),
        archivo = coalesce(excluded.archivo, p.archivo),
        eta = coalesce(excluded.eta, p.eta),
        actualizado_en = now()
  returning id into v_id;

  delete from wms_pl_contenedor_detalle where pl_id = v_id;
  insert into wms_pl_contenedor_detalle (pl_id, sku, descripcion, lote, vencimiento, cajas, multiplo, unidades)
  select v_id, upper(btrim(x->>'sku')), x->>'descripcion', nullif(btrim(x->>'lote'), ''), nullif(btrim(x->>'vencimiento'), ''),
         nullif(x->>'cajas', '')::numeric::int, nullif(x->>'multiplo', '')::numeric::int, nullif(x->>'unidades', '')::numeric::int
    from jsonb_array_elements(coalesce(p_lineas, '[]'::jsonb)) x
   where nullif(btrim(x->>'sku'), '') is not null;

  update wms_pl_contenedores p
     set cajas = d.cajas, unidades = d.unidades, lineas = d.lineas
    from (select sum(cajas)::int cajas, sum(unidades)::int unidades, count(*)::int lineas
            from wms_pl_contenedor_detalle where pl_id = v_id) d
   where p.id = v_id;
  return jsonb_build_object('id', v_id, 'numero_oc', v_oc, 'contenedor', v_cont,
                            'lineas', (select lineas from wms_pl_contenedores where id = v_id));
end $$;

create or replace function public.wms_pl_eliminar(p_id bigint)
returns void language sql security definer set search_path = public as $$
  delete from wms_pl_contenedores where id = p_id;
$$;

-- ---------------------------------------------------------------------
-- 3. Contenedores de una OC (PL, legado del ASN, citas y recepciones) con su estado
-- ---------------------------------------------------------------------
create or replace function public.wms_oc_contenedores_base(p_numero_oc text)
returns table (contenedor text, tiene_pl boolean, pl_id bigint, referencia_pl text, nota_pl text, unidades_pl integer,
               cajas_pl integer, lineas_pl integer, cita date, hora_cita text, unidades_recibidas integer,
               pallets integer, primera_recepcion timestamptz, ultima_recepcion timestamptz, reporte_enviado boolean,
               estado text)
language sql stable security definer set search_path = public as $$
  with oc as (select public.wms_numero_oc(p_numero_oc) n),
  asns as (select a.id, public.wms_contenedor_normal(a.contenedor_referencia) cont
             from asn_cabecera a, oc where public.wms_numero_oc(a.numero_oc) = oc.n),
  pls as (select p.* from wms_pl_contenedores p, oc where p.numero_oc = oc.n),
  conts as (   -- todos los contenedores conocidos de la OC
    select contenedor c from pls
    union select cont from asns where cont is not null
    union select public.wms_contenedor_normal(g.contenedor) from wms_agenda_contenedores g, oc
           where g.estado = 'AGENDADO' and g.numero_oc = oc.n
    union select public.wms_contenedor_normal(x.contenedor) from registro_recepcion x
           where x.asn_id in (select id from asns) and coalesce(x.contenedor, '') !~* '^(PO-|SIN-CONTENEDOR)'
             and public.wms_contenedor_normal(x.contenedor) is not null
  ),
  unico as (select count(*) = 1 solo from conts),
  rec as (     -- lo recibido por contenedor (si la OC tiene un solo contenedor, también lo recibido como 'PO-id')
    select c.c,
           sum(x.unidades_totales)::int un, count(distinct x.lpn)::int pallets,
           min(coalesce(x.fecha_recepcion, x.created_at)) primera, max(coalesce(x.fecha_recepcion, x.created_at)) ultima
      from conts c cross join unico
      join registro_recepcion x
        on public.wms_contenedor_normal(x.contenedor) = c.c
        or (unico.solo and x.asn_id in (select id from asns) and coalesce(x.contenedor, '') ~* '^PO-')
     group by c.c
  )
  select c.c,
         (p.id is not null or exists (select 1 from asns where cont = c.c)),
         p.id, p.referencia_pl, p.nota,
         coalesce(p.unidades, (select sum(coalesce(d.unidades_packing_list, d.unidades_esperadas))::int
                                 from asn_detalle d where d.asn_id in (select id from asns where cont = c.c))),
         coalesce(p.cajas, (select sum(coalesce(d.cajas_packing_list, d.cajas_esperadas))::int
                              from asn_detalle d where d.asn_id in (select id from asns where cont = c.c))),
         p.lineas,
         g.fecha_cita, g.hora_cita,
         coalesce(r.un, 0), coalesce(r.pallets, 0), r.primera, r.ultima,
         exists (select 1 from wms_reportes_recepcion w
                  where public.wms_contenedor_normal(w.contenedor) = c.c
                     or (unico.solo and w.asn_id in (select id from asns))),
         case
           when exists (select 1 from wms_reportes_recepcion w
                         where public.wms_contenedor_normal(w.contenedor) = c.c
                            or (unico.solo and w.asn_id in (select id from asns))) then 'RECIBIDO'
           when coalesce(r.un, 0) > 0 and coalesce(p.unidades, 0) > 0 and r.un >= p.unidades then 'RECIBIDO'
           when coalesce(r.un, 0) > 0 then 'EN_RECEPCION'
           when g.fecha_cita is not null and g.fecha_cita < current_date then 'CITA_VENCIDA'
           when g.fecha_cita is not null then 'AGENDADO'
           when p.id is not null or exists (select 1 from asns where cont = c.c) then 'PL_CARGADO'
           else 'SIN_PL' end
    from conts c
    cross join unico
    left join pls p on p.contenedor = c.c
    left join rec r on r.c = c.c
    left join lateral (select g.fecha_cita, g.hora_cita from wms_agenda_contenedores g
                        where g.estado = 'AGENDADO' and public.wms_contenedor_normal(g.contenedor) = c.c
                        order by g.fecha_cita desc limit 1) g on true
   where c.c is not null
   order by coalesce(g.fecha_cita, p.eta, current_date + 365), c.c;
$$;

create or replace function public.wms_oc_contenedores(p_numero_oc text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'oc', (select to_jsonb(n) || jsonb_build_object('cargada_ns', public.wms_oc_estado_ns_recepcion(n.numero_oc))
             from wms_oc_netsuite n where n.numero_oc = public.wms_numero_oc(p_numero_oc)),
    'asn', (select jsonb_agg(jsonb_build_object('id', a.id, 'codigo_asn', a.codigo_asn, 'estado', a.estado,
                                                'contenedor', a.contenedor_referencia, 'bodega', a.bodega) order by a.id)
              from asn_cabecera a where public.wms_numero_oc(a.numero_oc) = public.wms_numero_oc(p_numero_oc)),
    'contenedores', coalesce((select jsonb_agg(to_jsonb(b)) from public.wms_oc_contenedores_base(p_numero_oc) b), '[]'::jsonb),
    'recibido_sin_contenedor', coalesce((
        select sum(x.unidades_totales)::int from registro_recepcion x
         where x.asn_id in (select id from asn_cabecera a where public.wms_numero_oc(a.numero_oc) = public.wms_numero_oc(p_numero_oc))
           and coalesce(x.contenedor, '') ~* '^PO-'
           and (select count(*) from public.wms_oc_contenedores_base(p_numero_oc)) <> 1), 0)
  );
$$;

-- Detalle de un contenedor: lo que trae el PL contra lo recibido, por SKU
create or replace function public.wms_oc_contenedor_detalle(p_numero_oc text, p_contenedor text)
returns jsonb language sql stable security definer set search_path = public as $$
  with oc as (select public.wms_numero_oc(p_numero_oc) n, public.wms_contenedor_normal(p_contenedor) c),
  asns as (select a.id, public.wms_contenedor_normal(a.contenedor_referencia) cont
             from asn_cabecera a, oc where public.wms_numero_oc(a.numero_oc) = oc.n),
  pl as (select p.* from wms_pl_contenedores p, oc where p.numero_oc = oc.n and p.contenedor = oc.c),
  base as (select * from public.wms_oc_contenedores_base(p_numero_oc)),
  esperado as (
    select upper(d.sku) sku, max(d.descripcion) descripcion,
           string_agg(distinct d.lote, ', ') lotes, string_agg(distinct d.vencimiento, ', ') vencimientos,
           sum(d.cajas)::int cajas, sum(d.unidades)::int unidades
      from wms_pl_contenedor_detalle d where d.pl_id in (select id from pl)
     group by 1
    union all   -- PL antiguo (en el ASN de la OC) cuando no hay PL por contenedor
    select upper(d.sku), max(d.descripcion_proveedor), string_agg(distinct d.lote_sugerido, ', '),
           string_agg(distinct d.vencimiento_sugerido_cl, ', '),
           sum(coalesce(d.cajas_packing_list, d.cajas_esperadas))::int, sum(coalesce(d.unidades_packing_list, d.unidades_esperadas))::int
      from asn_detalle d, oc
     where not exists (select 1 from pl) and d.asn_id in (select id from asns where cont = oc.c)
     group by 1
  ),
  recibido as (
    select upper(btrim(x.sku)) sku, sum(x.unidades_totales)::int unidades, sum(x.cajas)::int cajas,
           count(distinct x.lpn)::int pallets, string_agg(distinct coalesce(x.lote, 'S/L'), ', ') lotes
      from registro_recepcion x, oc
     where public.wms_contenedor_normal(x.contenedor) = oc.c
        or ((select count(*) from base) = 1 and x.asn_id in (select id from asns) and coalesce(x.contenedor, '') ~* '^PO-')
     group by 1
  )
  select jsonb_build_object(
    'contenedor', (select to_jsonb(b) from base b, oc where b.contenedor = oc.c),
    'pl', (select to_jsonb(p) from pl p),
    'lineas', coalesce((
      select jsonb_agg(jsonb_build_object(
               'sku', coalesce(e.sku, r.sku),
               'descripcion', coalesce(e.descripcion, (select m.descripcion from maestra_sku m where upper(m.sku) = coalesce(e.sku, r.sku)
                                                        and nullif(btrim(m.descripcion), '') is not null limit 1)),
               'lotes_pl', e.lotes, 'vencimientos_pl', e.vencimientos,
               'cajas_pl', e.cajas, 'unidades_pl', e.unidades,
               'cajas_recibidas', coalesce(r.cajas, 0), 'unidades_recibidas', coalesce(r.unidades, 0),
               'lotes_recibidos', r.lotes, 'pallets', coalesce(r.pallets, 0),
               'diferencia', coalesce(r.unidades, 0) - coalesce(e.unidades, 0),
               'fuera_de_pl', e.sku is null)
             order by coalesce(e.sku, r.sku))
        from esperado e full join recibido r on r.sku = e.sku), '[]'::jsonb)
  );
$$;

-- ---------------------------------------------------------------------
-- 4. Marcas y OC abiertas por marca
-- ---------------------------------------------------------------------
create or replace function public.wms_oc_marcas()
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(m order by m.ocs desc, m.marca), '[]'::jsonb)
    from (select coalesce(nullif(btrim(n.proveedor), ''), 'SIN PROVEEDOR') marca,
                 count(*)::int ocs, sum(n.unidades)::bigint unidades, min(n.fecha_oc) mas_antigua,
                 count(*) filter (where exists (select 1 from wms_pl_contenedores p where p.numero_oc = n.numero_oc)
                                     or exists (select 1 from asn_cabecera a where public.wms_numero_oc(a.numero_oc) = n.numero_oc))::int con_pl
            from wms_oc_netsuite n where n.abierta
           group by 1) m;
$$;

create or replace function public.wms_oc_por_marca(p_marca text)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(x order by x.fecha_oc, x.numero_oc), '[]'::jsonb) from (
    select n.numero_oc, n.tranid, n.proveedor, n.fecha_oc, n.creada_en, n.fecha_esperada, n.estado_ns, n.nota,
           n.unidades, n.lineas, n.ubicacion,
           (current_date - n.fecha_oc) dias_abierta,
           public.wms_oc_estado_ns_recepcion(n.numero_oc) cargada_ns,
           exists (select 1 from asn_cabecera a where public.wms_numero_oc(a.numero_oc) = n.numero_oc) en_wms,
           c.contenedores, c.con_pl, c.recibidos, c.en_recepcion, c.agendados, c.unidades_pl, c.unidades_recibidas,
           c.proxima_cita
      from wms_oc_netsuite n
      left join lateral (
        select count(*)::int contenedores,
               count(*) filter (where b.tiene_pl)::int con_pl,
               count(*) filter (where b.estado = 'RECIBIDO')::int recibidos,
               count(*) filter (where b.estado = 'EN_RECEPCION')::int en_recepcion,
               count(*) filter (where b.estado in ('AGENDADO', 'CITA_VENCIDA'))::int agendados,
               sum(b.unidades_pl)::int unidades_pl, sum(b.unidades_recibidas)::int unidades_recibidas,
               min(b.cita) filter (where b.cita >= current_date) proxima_cita
          from public.wms_oc_contenedores_base(n.numero_oc) b) c on true
     where n.abierta and coalesce(nullif(btrim(n.proveedor), ''), 'SIN PROVEEDOR') = p_marca
  ) x;
$$;

-- ---------------------------------------------------------------------
-- 5. Celular: contenedores de la OC elegida (para recibir uno por uno)
-- ---------------------------------------------------------------------
create or replace function public.wms_app_contenedores_oc(p_asn_id bigint)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('contenedor', b.contenedor, 'estado', b.estado,
                                               'unidades_pl', b.unidades_pl, 'unidades_recibidas', b.unidades_recibidas,
                                               'cita', b.cita, 'nota', b.nota_pl)), '[]'::jsonb)
    from asn_cabecera a, public.wms_oc_contenedores_base(a.numero_oc) b
   where a.id = p_asn_id;
$$;

