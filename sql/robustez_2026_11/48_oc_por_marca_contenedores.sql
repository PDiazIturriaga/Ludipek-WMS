create table if not exists public.wms_pl_contenedores (
  id             bigint generated by default as identity primary key,
  numero_oc      text not null,
  contenedor     text not null,
  referencia_pl  text,
  proveedor      text,
  asn_id         bigint,
  eta            date,
  nota           text,
  archivo        text,
  cajas          integer,
  unidades       integer,
  lineas         integer,
  creado_por     text,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (numero_oc, contenedor)
);
create table if not exists public.wms_pl_contenedor_detalle (
  id          bigint generated by default as identity primary key,
  pl_id       bigint not null references public.wms_pl_contenedores(id) on delete cascade,
  sku         text not null,
  descripcion text,
  lote        text,
  vencimiento text,
  cajas       integer,
  multiplo    integer,
  unidades    integer
);
create index if not exists ix_pl_det_pl on public.wms_pl_contenedor_detalle (pl_id);
alter table public.wms_pl_contenedores enable row level security;
alter table public.wms_pl_contenedor_detalle enable row level security;
