-- misma lectura que en 45, ahora con la nota completa (antes se cortaba en 300 caracteres)
create or replace function public.wms_oc_sincronizar(p_filas jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_n int := 0;
  v_nuevas int := 0;
  f jsonb;
  v_num text;
begin
  for f in select * from jsonb_array_elements(coalesce(p_filas, '[]'::jsonb)) loop
    v_num := public.wms_numero_oc(f->>'tranid');
    continue when v_num is null;
    if not exists (select 1 from wms_oc_netsuite where numero_oc = v_num) then v_nuevas := v_nuevas + 1; end if;
    insert into wms_oc_netsuite (numero_oc, ns_id, tranid, proveedor, ubicacion, estado_ns, fecha_oc, creada_en,
                                 fecha_esperada, unidades, lineas, nota)
    values (v_num, nullif(f->>'ns_id', '')::numeric::bigint, f->>'tranid', f->>'proveedor', f->>'ubicacion', f->>'estado_ns',
            nullif(f->>'fecha_oc', '')::date,
            (nullif(f->>'creada_en', '')::timestamp at time zone 'America/Santiago'),
            nullif(f->>'fecha_esperada', '')::date, nullif(f->>'unidades', '')::numeric,
            nullif(f->>'lineas', '')::numeric::int, left(f->>'nota', 4000))
    on conflict (numero_oc) do update
      set ns_id = excluded.ns_id, tranid = excluded.tranid, proveedor = excluded.proveedor,
          ubicacion = coalesce(excluded.ubicacion, wms_oc_netsuite.ubicacion), estado_ns = excluded.estado_ns,
          fecha_oc = excluded.fecha_oc,
          creada_en = coalesce(excluded.creada_en, wms_oc_netsuite.creada_en),
          fecha_esperada = coalesce(excluded.fecha_esperada, wms_oc_netsuite.fecha_esperada),
          unidades = coalesce(excluded.unidades, wms_oc_netsuite.unidades),
          lineas = coalesce(excluded.lineas, wms_oc_netsuite.lineas),
          nota = excluded.nota, sincronizada_en = now();
    v_n := v_n + 1;
  end loop;
  return jsonb_build_object('leidas', v_n, 'nuevas', v_nuevas,
                            'ultima_sincronizacion', (select max(sincronizada_en) from wms_oc_netsuite));
end $$;

-- p_filas: TODAS las OC abiertas en NetSuite. Las que estaban abiertas y ya no vienen quedan cerradas.
create or replace function public.wms_oc_sincronizar_abiertas(p_filas jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_res jsonb;
  v_cerradas int;
begin
  v_res := public.wms_oc_sincronizar(p_filas);
  update wms_oc_netsuite n set abierta = true, abierta_revisada_en = now()
   where n.numero_oc in (select public.wms_numero_oc(x->>'tranid') from jsonb_array_elements(coalesce(p_filas, '[]'::jsonb)) x);
  update wms_oc_netsuite n set abierta = false, abierta_revisada_en = now()
   where n.abierta
     and n.numero_oc not in (select public.wms_numero_oc(x->>'tranid') from jsonb_array_elements(coalesce(p_filas, '[]'::jsonb)) x
                             where public.wms_numero_oc(x->>'tranid') is not null);
  get diagnostics v_cerradas = row_count;
  return v_res || jsonb_build_object('abiertas', jsonb_array_length(coalesce(p_filas, '[]'::jsonb)), 'cerradas', v_cerradas);
end $$;

