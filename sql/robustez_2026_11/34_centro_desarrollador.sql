-- =====================================================================
-- LUDIPEK WMS · 34 CENTRO DEL DESARROLLADOR: ERRORES AGRUPADOS Y TICKETS  (requiere 24, 26 y 31)
--
-- · Errores: cada error que llega a wms_log_errores (celular o PC) se agrupa por "firma"
--   (el mismo mensaje sin números). Cada grupo tiene estado: NUEVO, EN_REVISION, RESUELTO,
--   IGNORADO. Si un error RESUELTO vuelve a ocurrir, el grupo pasa a REAPARECIO.
-- · Tickets: cualquier usuario puede "Reportar un problema" desde el PC o el celular.
--   El desarrollador los gestiona (estado, prioridad, comentarios, respuesta al usuario).
-- · Módulo PC "Desarrollador" (permiso PC_DESARROLLADOR): no lo abre nadie que no tenga
--   ese permiso marcado explícitamente, ni siquiera los ADMIN.
-- =====================================================================
begin;

-- ---------------------------------------------------------------------
-- 1. Firma de un error (mismo error aunque cambie un LPN, un id o una hora)
-- ---------------------------------------------------------------------
create or replace function public.wms_firma_error(p_origen text, p_mensaje text)
returns text language sql immutable as $$
  select md5(upper(coalesce(p_origen, '')) || '|' ||
             left(regexp_replace(regexp_replace(lower(coalesce(p_mensaje, '')),
                                                '[0-9]+', '#', 'g'),
                                 '\s+', ' ', 'g'), 240))
$$;

alter table public.wms_log_errores add column if not exists firma text;
create index if not exists idx_log_errores_firma on public.wms_log_errores (firma, creado_en desc);

create table if not exists public.wms_errores_grupos (
  firma          text primary key,
  origen         text not null,
  modulo         text,
  mensaje        text not null,
  estado         text not null default 'NUEVO'
                 check (estado in ('NUEVO', 'EN_REVISION', 'RESUELTO', 'IGNORADO', 'REAPARECIO')),
  ocurrencias    integer not null default 0,
  primera_vez    timestamptz not null default now(),
  ultima_vez     timestamptz not null default now(),
  ultima_version text,
  nota           text,
  ticket_id      bigint,
  actualizado_por text,
  actualizado_en timestamptz,
  resuelto_en    timestamptz
);
create index if not exists idx_errores_grupos_ultima on public.wms_errores_grupos (ultima_vez desc);
alter table public.wms_errores_grupos enable row level security;
revoke all on public.wms_errores_grupos from anon, authenticated;

create or replace function public.wms_tg_agrupar_error()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.firma := public.wms_firma_error(new.origen, new.mensaje);
  insert into wms_errores_grupos as g (firma, origen, modulo, mensaje, ocurrencias, primera_vez, ultima_vez, ultima_version)
  values (new.firma, new.origen, new.modulo, new.mensaje, 1, new.creado_en, new.creado_en, new.version_app)
  on conflict (firma) do update
     set ocurrencias = g.ocurrencias + 1,
         ultima_vez = greatest(g.ultima_vez, excluded.ultima_vez),
         ultima_version = coalesce(excluded.ultima_version, g.ultima_version),
         modulo = coalesce(excluded.modulo, g.modulo),
         mensaje = excluded.mensaje,
         estado = case when g.estado = 'RESUELTO' then 'REAPARECIO' else g.estado end;
  return new;
exception when others then
  return new;      -- agrupar nunca debe impedir que se guarde el error
end $$;

drop trigger if exists tg_agrupar_error on public.wms_log_errores;
create trigger tg_agrupar_error before insert on public.wms_log_errores
  for each row execute function public.wms_tg_agrupar_error();

-- Errores ya guardados: calcular su firma y armar los grupos
update public.wms_log_errores set firma = public.wms_firma_error(origen, mensaje) where firma is null;
insert into public.wms_errores_grupos (firma, origen, modulo, mensaje, ocurrencias, primera_vez, ultima_vez, ultima_version)
select distinct on (l.firma) l.firma, l.origen, l.modulo, l.mensaje,
       count(*) over (partition by l.firma), min(l.creado_en) over (partition by l.firma),
       max(l.creado_en) over (partition by l.firma), l.version_app
  from public.wms_log_errores l
 order by l.firma, l.creado_en desc
on conflict (firma) do nothing;

-- ---------------------------------------------------------------------
-- 2. Tickets
-- ---------------------------------------------------------------------
create table if not exists public.wms_tickets (
  id             bigint generated by default as identity primary key,
  origen         text not null default 'PC' check (origen in ('PC', 'RF', 'DEV')),
  tipo           text not null default 'PROBLEMA' check (tipo in ('PROBLEMA', 'ERROR', 'MEJORA', 'CONSULTA')),
  titulo         text not null,
  descripcion    text,
  modulo         text,
  usuario        text,
  bodega         text,
  version_app    text,
  dispositivo    text,
  prioridad      text not null default 'MEDIA' check (prioridad in ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
  estado         text not null default 'NUEVO'
                 check (estado in ('NUEVO', 'EN_REVISION', 'EN_DESARROLLO', 'RESUELTO', 'DESCARTADO')),
  firma_error    text,
  respuesta      text,                -- lo que ve el usuario que reportó
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  resuelto_en    timestamptz
);
create index if not exists idx_tickets_estado on public.wms_tickets (estado, creado_en desc);
create index if not exists idx_tickets_usuario on public.wms_tickets (usuario, creado_en desc);
alter table public.wms_tickets enable row level security;
revoke all on public.wms_tickets from anon, authenticated;

create table if not exists public.wms_tickets_comentarios (
  id         bigint generated by default as identity primary key,
  ticket_id  bigint not null references public.wms_tickets(id) on delete cascade,
  usuario    text,
  texto      text not null,
  interno    boolean not null default true,     -- true = solo lo ve el desarrollador
  creado_en  timestamptz not null default now()
);
create index if not exists idx_tickets_com on public.wms_tickets_comentarios (ticket_id, id);
alter table public.wms_tickets_comentarios enable row level security;
revoke all on public.wms_tickets_comentarios from anon, authenticated;

do $$ begin
  alter table public.wms_errores_grupos
    add constraint wms_errores_grupos_ticket_fk foreign key (ticket_id) references public.wms_tickets(id) on delete set null;
exception when duplicate_object then null;
end $$;
create index if not exists idx_errores_grupos_ticket on public.wms_errores_grupos (ticket_id);

grant select, insert, update, delete on public.wms_errores_grupos, public.wms_tickets, public.wms_tickets_comentarios
  to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Reportar un problema (celular y PC). El usuario lo toma de la sesión verificada si la hay.
create or replace function public.wms_reportar_problema(
  p_origen text, p_modulo text, p_tipo text, p_titulo text, p_descripcion text,
  p_usuario text default null, p_bodega text default null, p_version text default null,
  p_dispositivo text default null, p_prioridad text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_usuario text;
  v_id bigint;
  v_tipo text := upper(btrim(coalesce(p_tipo, 'PROBLEMA')));
  v_prio text := upper(btrim(coalesce(p_prioridad, 'MEDIA')));
  v_titulo text := left(btrim(coalesce(p_titulo, '')), 140);
begin
  begin
    v_usuario := public.wms_usuario_efectivo(p_usuario);
  exception when others then
    v_usuario := upper(btrim(coalesce(p_usuario, '')));
  end;
  if length(v_titulo) < 4 then
    raise exception 'WMS: escriba en pocas palabras qué pasó (título).';
  end if;
  if v_tipo not in ('PROBLEMA', 'ERROR', 'MEJORA', 'CONSULTA') then v_tipo := 'PROBLEMA'; end if;
  if v_prio not in ('BAJA', 'MEDIA', 'ALTA', 'CRITICA') then v_prio := 'MEDIA'; end if;
  if (select count(*) from wms_tickets where coalesce(usuario, '') = coalesce(v_usuario, '')
        and creado_en > now() - interval '1 hour') >= 15 then
    raise exception 'WMS: demasiados reportes en la última hora. Espere un momento.';
  end if;
  insert into wms_tickets (origen, tipo, titulo, descripcion, modulo, usuario, bodega, version_app, dispositivo, prioridad)
  values (case when upper(coalesce(p_origen, '')) in ('PC', 'RF', 'DEV') then upper(p_origen) else 'RF' end,
          v_tipo, v_titulo, left(nullif(btrim(coalesce(p_descripcion, '')), ''), 4000),
          left(nullif(btrim(coalesce(p_modulo, '')), ''), 80), nullif(v_usuario, ''),
          left(nullif(btrim(coalesce(p_bodega, '')), ''), 40), left(nullif(btrim(coalesce(p_version, '')), ''), 30),
          left(nullif(btrim(coalesce(p_dispositivo, '')), ''), 120), v_prio)
  returning id into v_id;
  return jsonb_build_object('id', v_id);
end $$;

-- Mis reportes: lo que ve el usuario (estado y respuesta; no ve las notas internas)
create or replace function public.wms_mis_tickets(p_usuario text default null)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_usuario text;
begin
  begin
    v_usuario := public.wms_usuario_efectivo(p_usuario);
  exception when others then
    v_usuario := upper(btrim(coalesce(p_usuario, '')));
  end;
  if coalesce(v_usuario, '') = '' then return '[]'::jsonb; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', t.id, 'tipo', t.tipo, 'titulo', t.titulo, 'estado', t.estado, 'modulo', t.modulo,
             'creado', to_char(t.creado_en at time zone 'America/Santiago', 'DD-MM-YYYY HH24:MI'),
             'actualizado', to_char(t.actualizado_en at time zone 'America/Santiago', 'DD-MM-YYYY HH24:MI'),
             'respuesta', t.respuesta,
             'comentarios', coalesce((select jsonb_agg(jsonb_build_object('usuario', c.usuario, 'texto', c.texto,
                                         'fecha', to_char(c.creado_en at time zone 'America/Santiago', 'DD-MM HH24:MI'))
                                       order by c.id)
                                      from wms_tickets_comentarios c where c.ticket_id = t.id and not c.interno), '[]'::jsonb)
           ) order by t.id desc)
      from (select * from wms_tickets where usuario = v_usuario order by id desc limit 25) t), '[]'::jsonb);
end $$;

-- ---------------------------------------------------------------------
-- 3. Resumen para el módulo Desarrollador (solo PC)
-- ---------------------------------------------------------------------
create or replace function public.wms_dev_resumen(p_dias integer default 14)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_dias int := least(greatest(coalesce(p_dias, 14), 7), 60);
  v_hoy date := (now() at time zone 'America/Santiago')::date;
begin
  return jsonb_build_object(
    'generado', to_char(now() at time zone 'America/Santiago', 'DD-MM-YYYY HH24:MI'),
    'version_minima', (select valor from wms_config where clave = 'version_minima_rf'),
    'kpis', jsonb_build_object(
      'errores_24h', (select count(*) from wms_log_errores where creado_en > now() - interval '24 hours'),
      'errores_24h_rf', (select count(*) from wms_log_errores where creado_en > now() - interval '24 hours' and origen = 'RF'),
      'usuarios_24h', (select count(distinct usuario) from wms_log_errores where creado_en > now() - interval '24 hours'),
      'grupos_pendientes', (select count(*) from wms_errores_grupos where estado in ('NUEVO', 'REAPARECIO', 'EN_REVISION')),
      'grupos_nuevos', (select count(*) from wms_errores_grupos where estado = 'NUEVO'),
      'reaparecidos', (select count(*) from wms_errores_grupos where estado = 'REAPARECIO'),
      'tickets_abiertos', (select count(*) from wms_tickets where estado in ('NUEVO', 'EN_REVISION', 'EN_DESARROLLO')),
      'tickets_nuevos', (select count(*) from wms_tickets where estado = 'NUEVO'),
      'tickets_urgentes', (select count(*) from wms_tickets where estado in ('NUEVO', 'EN_REVISION', 'EN_DESARROLLO')
                                                                and prioridad in ('ALTA', 'CRITICA'))
    ),
    'por_dia', (
      select coalesce(jsonb_agg(jsonb_build_object(
               'dia', to_char(d, 'DD-MM'),
               'rf', (select count(*) from wms_log_errores l where l.origen = 'RF'
                        and (l.creado_en at time zone 'America/Santiago')::date = d),
               'pc', (select count(*) from wms_log_errores l where l.origen <> 'RF'
                        and (l.creado_en at time zone 'America/Santiago')::date = d)) order by d), '[]'::jsonb)
      from generate_series(v_hoy - (v_dias - 1), v_hoy, interval '1 day') g(d0), lateral (select g.d0::date d) x
    ),
    'por_modulo', (
      select coalesce(jsonb_agg(jsonb_build_object('modulo', modulo, 'origen', origen, 'n', n) order by n desc), '[]'::jsonb)
      from (select coalesce(modulo, '-') modulo, origen, count(*) n from wms_log_errores
             where creado_en > now() - make_interval(days => v_dias)
             group by 1, 2 order by 3 desc limit 8) z
    ),
    -- Celulares con sesión usada en las últimas 24 h (la versión viaja en "dispositivo" desde la app 2026.11.20.8)
    'sesiones', (
      select coalesce(jsonb_agg(jsonb_build_object(
               'usuario', s.usuario, 'nombre', s.nombre, 'bodega', s.bodega, 'dispositivo', s.dispositivo,
               'version', substring(coalesce(s.dispositivo, '') from 'v([0-9]+(\.[0-9]+)+)'),
               'ultimo_uso', to_char(s.ultimo_uso at time zone 'America/Santiago', 'DD-MM HH24:MI'),
               'abierta', s.cerrada_en is null) order by s.ultimo_uso desc), '[]'::jsonb)
      from wms_sesiones s where s.ultimo_uso > now() - interval '24 hours'
    ),
    -- Última versión con la que cada usuario reportó un error (sirve también para el PC)
    'versiones_errores', (
      select coalesce(jsonb_agg(jsonb_build_object('usuario', usuario, 'origen', origen, 'version', version_app,
                                                   'fecha', to_char(creado_en at time zone 'America/Santiago', 'DD-MM HH24:MI'))
                                order by creado_en desc), '[]'::jsonb)
      from (select distinct on (usuario, origen) usuario, origen, version_app, creado_en
              from wms_log_errores where creado_en > now() - interval '7 days' and coalesce(usuario, '') <> ''
             order by usuario, origen, creado_en desc) z
    )
  );
end $$;

