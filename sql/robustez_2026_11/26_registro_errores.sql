-- =====================================================================
-- LUDIPEK WMS · 26 REGISTRO CENTRAL DE ERRORES  (requiere 24)
-- Los errores inesperados del celular y del PC (no las validaciones normales como
-- "el LPN no existe") quedan guardados en wms_log_errores con módulo, usuario y versión.
-- El PC los muestra en "Requiere atención" (después de este script vuelva a ejecutar el 14).
-- Un mismo error del mismo usuario se guarda una sola vez por minuto, y se borran
-- solos los registros de más de 90 días.
-- =====================================================================
begin;

create table if not exists public.wms_log_errores (
  id          bigint generated by default as identity primary key,
  creado_en   timestamptz not null default now(),
  origen      text not null,              -- RF (celular) o PC
  modulo      text,
  usuario     text,
  bodega      text,
  version_app text,
  mensaje     text not null,
  detalle     text
);
alter table public.wms_log_errores enable row level security;   -- sin políticas: solo la función y el PC
revoke all on public.wms_log_errores from anon, authenticated;
create index if not exists idx_log_errores_fecha on public.wms_log_errores (creado_en desc);

create or replace function public.wms_registrar_error(
  p_origen text, p_modulo text, p_mensaje text, p_detalle text default null,
  p_version text default null, p_usuario text default null, p_bodega text default null)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_usuario text;
  v_msg text := left(btrim(coalesce(p_mensaje, '')), 500);
begin
  if v_msg = '' then return; end if;
  begin
    v_usuario := public.wms_usuario_efectivo(p_usuario);
  exception when others then
    v_usuario := upper(btrim(coalesce(p_usuario, '')));
  end;
  -- el mismo error del mismo usuario, una vez por minuto
  if exists (select 1 from wms_log_errores
             where creado_en > now() - interval '1 minute' and mensaje = v_msg
               and coalesce(usuario, '') = coalesce(v_usuario, '')) then
    return;
  end if;
  insert into wms_log_errores (origen, modulo, usuario, bodega, version_app, mensaje, detalle)
  values (left(upper(coalesce(nullif(btrim(p_origen), ''), 'RF')), 10), left(nullif(btrim(coalesce(p_modulo, '')), ''), 60),
          v_usuario, left(nullif(btrim(coalesce(p_bodega, '')), ''), 40), left(nullif(btrim(coalesce(p_version, '')), ''), 30),
          v_msg, left(nullif(btrim(coalesce(p_detalle, '')), ''), 4000));
  -- limpieza ocasional
  if random() < 0.02 then
    delete from wms_log_errores where creado_en < now() - interval '90 days';
  end if;
exception when others then
  null;   -- registrar un error nunca debe provocar otro
end $$;

grant execute on function public.wms_registrar_error(text, text, text, text, text, text, text) to anon, authenticated, service_role;

commit;

