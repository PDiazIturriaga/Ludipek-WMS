-- Reemplaza las aplicaciones aparte (app_lpn.py con memoria_lpn.txt y app_cencosud.py
-- con correlativo_config.json + Historico_Cencosud.xlsx). Ahora los correlativos viven en
-- Supabase: dos personas imprimiendo a la vez nunca reciben el mismo número.
--
--   LPN Santiago    : continúa desde LPN-100654 (último de memoria_lpn.txt) o desde el mayor
--                     LPN-1xxxxx que ya exista en la base, lo que sea mayor.
--   LPN Concepción  : rango propio desde LPN-500001 (no se cruza con Santiago).
--   HU Cencosud     : continúa desde 76661486000001950 (último HU usado en la OC 5578271058).
-- Revise la consulta final; si algún número no es el correcto, corríjalo con:
--   update public.wms_correlativos set ultimo = <ultimo usado> where clave = '<clave>';
-- =====================================================================
begin;

create table if not exists public.wms_correlativos (
  clave           text primary key,
  ultimo          bigint not null,
  descripcion     text,
  actualizado_en  timestamptz not null default now(),
  actualizado_por text
);
alter table public.wms_correlativos enable row level security;
revoke all on public.wms_correlativos from anon, authenticated;

-- Último LPN numérico que ya existe en la base para un rango (para no repetir)
create or replace function public.wms_max_lpn_rango(p_bodega text, p_min bigint, p_max bigint)
returns bigint language sql stable security definer set search_path = public as $$
  select max(n) from (
    select substring(upper(lpn) from '^LPN-(\d{6,7})$')::bigint n from registro_recepcion where bodega = p_bodega
    union all
    select substring(upper(lpn) from '^LPN-(\d{6,7})$')::bigint from bodega_inventario_ubicacion where bodega = p_bodega
  ) x
  where n between p_min and p_max;
$$;

insert into public.wms_correlativos (clave, ultimo, descripcion, actualizado_por) values
  ('LPN|Bodega Santiago',
   greatest(100654, coalesce(public.wms_max_lpn_rango('Bodega Santiago', 100000, 499999), 0)),
   'Último LPN impreso en Bodega Santiago (LPN-1xxxxx)', 'SCRIPT 27'),
  ('LPN|Bodega Concepcion',
   greatest(500000, coalesce(public.wms_max_lpn_rango('Bodega Concepcion', 500000, 899999), 0)),
   'Último LPN impreso en Bodega Concepción (LPN-5xxxxx)', 'SCRIPT 27'),
  ('CENCOSUD_HU', 76661486000001950, 'Último N° de HU usado en etiquetas Cencosud', 'SCRIPT 27')
on conflict (clave) do nothing;

-- Lotes de etiquetas LPN impresos (para reimprimir y auditar)
create table if not exists public.wms_lpn_lotes (
  id        bigint generated by default as identity primary key,
  bodega    text not null,
  desde     bigint not null,
  hasta     bigint not null,
  cantidad  integer not null,
  usuario   text,
  creado_en timestamptz not null default now()
);
alter table public.wms_lpn_lotes enable row level security;
revoke all on public.wms_lpn_lotes from anon, authenticated;
create index if not exists idx_lpn_lotes_bodega on public.wms_lpn_lotes (bodega, id desc);

-- Reserva N números de un correlativo de forma atómica. Devuelve el rango.
create or replace function public.wms_reservar_correlativo(p_clave text, p_cantidad integer, p_usuario text default null,
                                                          p_desde bigint default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  c record;
  v_desde bigint;
  v_hasta bigint;
begin
  if coalesce(p_cantidad, 0) < 1 or p_cantidad > 5000 then
    raise exception 'WMS: la cantidad debe estar entre 1 y 5000';
  end if;
  select * into c from wms_correlativos where clave = p_clave for update;
  if not found then
    raise exception 'WMS: el correlativo % no existe (ejecute 27_correlativos_impresion.sql)', p_clave;
  end if;
  -- p_desde permite partir en otro número (como el campo editable de la app antigua);
  -- el correlativo nunca retrocede.
  v_desde := coalesce(p_desde, c.ultimo + 1);
  v_hasta := v_desde + p_cantidad - 1;
  update wms_correlativos
     set ultimo = greatest(c.ultimo, v_hasta), actualizado_en = now(),
         actualizado_por = coalesce(nullif(upper(btrim(coalesce(p_usuario, ''))), ''), 'PC')
   where clave = p_clave;
  return jsonb_build_object('clave', p_clave, 'desde', v_desde, 'hasta', v_hasta, 'anterior', c.ultimo,
                            'siguiente', greatest(c.ultimo, v_hasta) + 1);
end $$;

-- LPN de una bodega: reserva el rango y deja registrado el lote
create or replace function public.wms_reservar_lpn(p_bodega text, p_cantidad integer, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_bodega text := public.wms_bodega_valida(p_bodega);
  r jsonb;
begin
  if coalesce(p_cantidad, 0) > 1000 then
    raise exception 'WMS: máximo 1000 etiquetas LPN por impresión';
  end if;
  r := public.wms_reservar_correlativo('LPN|' || v_bodega, p_cantidad, p_usuario);
  insert into wms_lpn_lotes (bodega, desde, hasta, cantidad, usuario)
  values (v_bodega, (r ->> 'desde')::bigint, (r ->> 'hasta')::bigint, p_cantidad,
          coalesce(nullif(upper(btrim(coalesce(p_usuario, ''))), ''), 'PC'));
  return r || jsonb_build_object('bodega', v_bodega);
end $$;

-- Histórico de HU Cencosud (reemplaza Historico_Cencosud.xlsx)
create table if not exists public.wms_cencosud_hu (
  id                bigint generated by default as identity primary key,
  fecha_proceso     timestamptz not null default now(),
  numero_orden      text not null,
  fecha_entrega     text,
  hu                text not null,
  cod_local         text,
  nombre_local      text,
  cod_cencosud      text,
  cod_proveedor     text,
  ean13             text,
  descripcion       text,
  empaques_pedidos  integer not null default 0,
  unidades_empaque  integer not null default 1,
  cantidad_total    integer not null default 0,
  usuario           text,
  origen            text not null default 'WMS'      -- WMS o IMPORTADO (desde el Excel antiguo)
);
alter table public.wms_cencosud_hu enable row level security;
revoke all on public.wms_cencosud_hu from anon, authenticated;
create index if not exists idx_cencosud_hu_hu on public.wms_cencosud_hu (hu);
create index if not exists idx_cencosud_hu_oc on public.wms_cencosud_hu (numero_orden);

revoke all on function public.wms_max_lpn_rango(text, bigint, bigint) from public, anon, authenticated;
revoke all on function public.wms_reservar_correlativo(text, integer, text, bigint) from public, anon, authenticated;
revoke all on function public.wms_reservar_lpn(text, integer, text) from public, anon, authenticated;
grant execute on function public.wms_max_lpn_rango(text, bigint, bigint) to service_role;
grant execute on function public.wms_reservar_correlativo(text, integer, text, bigint) to service_role;
grant execute on function public.wms_reservar_lpn(text, integer, text) to service_role;

commit;

