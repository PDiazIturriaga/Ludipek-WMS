-- =====================================================================
-- LUDIPEK WMS · 21 DAR DE BAJA UN PALLET (SOLO ADMINISTRADORES)  (requiere 04 y 04b)
-- Para pallets que salieron directo a un cliente (o ya no existen) y nunca se ajustaron.
--  · Pallet en el andén: su recepción queda CERRADO_SIN_UBICAR (no se borra; el avance
--    de la OC no cambia) y deja de aparecer como pendiente de ubicar.
--  · Pallet en una ubicación: se eliminan sus filas de stock en esa ubicación.
--  En ambos casos queda en el kardex (BAJA_PALLET, unidades en negativo) y una copia
--  completa en wms_bajas_pallet con el motivo y el usuario (permite revisarlo o revertirlo).
-- También agrega wms_lpns_en_anden: la misma regla de "pendiente de ubicar" que usa la
-- alerta del andén (no cuenta pallets ya almacenados y consumidos, ni recepciones cerradas).
-- =====================================================================
begin;

create table if not exists public.wms_bajas_pallet (
  id         bigint generated by default as identity primary key,
  bodega     text not null,
  lpn        text not null,
  origen     text not null,               -- ANDEN o la ubicación
  motivo     text not null,
  usuario    text not null,
  unidades   integer not null default 0,
  filas      jsonb not null,              -- copia de lo que se dio de baja
  creado_en  timestamptz not null default now()
);
alter table public.wms_bajas_pallet enable row level security;
create index if not exists idx_bajas_pallet_lpn on public.wms_bajas_pallet (bodega, lpn);

-- Administrador = rol que contiene ADMIN (se acepta el código de usuario o el nombre completo)
create or replace function public.wms_es_admin(p_usuario text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from wms_usuarios u
    where coalesce(u.activo, true)
      and upper(coalesce(u.rol, '')) like '%ADMIN%'
      and upper(btrim(coalesce(p_usuario, ''))) in (upper(btrim(coalesce(u.usuario, ''))), upper(btrim(coalesce(u.nombre_completo, ''))))
      and btrim(coalesce(p_usuario, '')) <> '');
$$;

-- LPN pendientes de ubicar (andén)
create or replace function public.wms_lpns_en_anden(p_bodega text)
returns table (lpn text) language sql stable security definer set search_path = public as $$
  select distinct upper(btrim(r.lpn))
  from registro_recepcion r
  where r.bodega = public.wms_bodega_valida(p_bodega)
    and coalesce(btrim(r.lpn), '') <> ''
    and coalesce(r.estado_pallet, '') not in ('ALMACENADO', 'CERRADO_SIN_UBICAR')
    and not exists (select 1 from bodega_inventario_ubicacion i where i.bodega = r.bodega and i.lpn = r.lpn)
    and not exists (select 1 from historial_movimientos h where h.bodega = r.bodega and h.lpn = r.lpn
                    and h.tipo_movimiento in ('ALMACENAMIENTO', 'ENVIO_MERMA'));
$$;

create or replace function public.wms_eliminar_pallet(
  p_bodega text, p_lpn text, p_ubicacion text, p_motivo text, p_usuario text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_bodega text := public.wms_bodega_valida(p_bodega);
  v_usuario text := public.wms_contexto(p_usuario, 'wms_eliminar_pallet');
  v_lpn text := upper(btrim(coalesce(p_lpn, '')));
  v_ub text := upper(btrim(coalesce(p_ubicacion, '')));
  v_motivo text := btrim(coalesce(p_motivo, ''));
  v_anden boolean;
  v_filas jsonb;
  v_un int := 0;
  v_n int := 0;
  v_ubic_stock text;
  v_max_obs int;
  r record;
begin
  if not public.wms_es_admin(p_usuario) then
    raise exception 'WMS: solo un administrador puede dar de baja un pallet';
  end if;
  if v_lpn = '' then raise exception 'WMS: falta el LPN'; end if;
  if length(v_motivo) < 4 then raise exception 'WMS: escriba el motivo de la baja'; end if;
  perform pg_advisory_xact_lock(hashtext('LPN|' || v_lpn));

  v_anden := v_ub = '' or v_ub like 'AND%' or v_ub in ('RECEPCION', 'ANDEN_TRANSITO', 'PENDIENTE');

  if v_anden then
    -- Si el pallet ya tiene stock en una ubicación, se da de baja desde esa ubicación
    select string_agg(distinct i.codigo_ubicacion, ', ') into v_ubic_stock
    from bodega_inventario_ubicacion i
    where i.bodega = v_bodega and i.lpn = v_lpn and i.cantidad_unidades > 0;
    if v_ubic_stock is not null then
      raise exception 'WMS: el LPN % está en % (no en el andén). Dé de baja la fila de esa ubicación.', v_lpn, v_ubic_stock;
    end if;

    select coalesce(jsonb_agg(to_jsonb(x) order by x.id), '[]'), coalesce(sum(x.unidades_totales), 0), count(*)
      into v_filas, v_un, v_n
    from registro_recepcion x
    where x.bodega = v_bodega and x.lpn = v_lpn
      and coalesce(x.estado_pallet, '') not in ('ALMACENADO', 'CERRADO_SIN_UBICAR');
    if v_n = 0 then
      raise exception 'WMS: el LPN % no está pendiente en el andén de % (ya se ubicó o se cerró)', v_lpn, v_bodega;
    end if;

    for r in select * from registro_recepcion x
             where x.bodega = v_bodega and x.lpn = v_lpn
               and coalesce(x.estado_pallet, '') not in ('ALMACENADO', 'CERRADO_SIN_UBICAR')
    loop
      perform public.wms_kardex(v_bodega, 'BAJA_PALLET', v_lpn, r.sku, r.lote, 'ANDEN', 'BAJA',
                                -coalesce(r.cajas, 0), -coalesce(r.unidades_totales, 0));
    end loop;

    select character_maximum_length into v_max_obs from information_schema.columns
     where table_schema = 'public' and table_name = 'registro_recepcion' and column_name = 'observaciones';
    update registro_recepcion x
       set estado_pallet = 'CERRADO_SIN_UBICAR',
           observaciones = left(btrim(coalesce(x.observaciones || ' | ', '') ||
                           'BAJA ' || to_char(now() at time zone 'America/Santiago', 'DD-MM-YYYY HH24:MI') ||
                           ' ' || v_usuario || ': ' || v_motivo), coalesce(v_max_obs, 4000))
     where x.bodega = v_bodega and x.lpn = v_lpn
       and coalesce(x.estado_pallet, '') not in ('ALMACENADO', 'CERRADO_SIN_UBICAR');
    v_ub := 'ANDEN';
  else
    v_ub := public.wms_normalizar_ubicacion(v_ub);
    select coalesce(jsonb_agg(to_jsonb(x) order by x.id), '[]'), coalesce(sum(x.cantidad_unidades), 0), count(*)
      into v_filas, v_un, v_n
    from bodega_inventario_ubicacion x
    where x.bodega = v_bodega and x.lpn = v_lpn and x.codigo_ubicacion = v_ub;
    if v_n = 0 then
      raise exception 'WMS: el LPN % no tiene stock en % (actualice la pantalla)', v_lpn, v_ub;
    end if;

    for r in select * from bodega_inventario_ubicacion x
             where x.bodega = v_bodega and x.lpn = v_lpn and x.codigo_ubicacion = v_ub
    loop
      perform public.wms_kardex(v_bodega, 'BAJA_PALLET', v_lpn, r.sku, r.lote, v_ub, 'BAJA',
                                -coalesce(r.cajas, 0), -coalesce(r.cantidad_unidades, 0));
    end loop;
    delete from bodega_inventario_ubicacion x
     where x.bodega = v_bodega and x.lpn = v_lpn and x.codigo_ubicacion = v_ub;
  end if;

  insert into wms_bajas_pallet (bodega, lpn, origen, motivo, usuario, unidades, filas)
  values (v_bodega, v_lpn, v_ub, v_motivo, v_usuario, v_un, v_filas);

  return jsonb_build_object('lpn', v_lpn, 'origen', v_ub, 'filas', v_n, 'unidades', v_un);
end $$;

grant execute on function public.wms_es_admin(text) to service_role;
grant execute on function public.wms_lpns_en_anden(text) to anon, authenticated, service_role;
grant execute on function public.wms_eliminar_pallet(text, text, text, text, text) to service_role;

commit;

