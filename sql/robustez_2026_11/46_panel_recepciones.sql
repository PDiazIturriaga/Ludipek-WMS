-- Clave de una recepción: con OC (ASN) o por contenedor si es libre
create or replace function public.wms_clave_recepcion(p_asn_id bigint, p_contenedor text)
returns text language sql immutable as $$
  select case when p_asn_id is not null then 'ASN:' || p_asn_id
              else 'CONT:' || coalesce(nullif(upper(btrim(coalesce(p_contenedor, ''))), ''), 'SIN-CONTENEDOR') end;
$$;

-- El celular finaliza la recepción del contenedor: queda en cola el reporte
create or replace function public.wms_recepcion_finalizar(p_bodega text, p_asn_id bigint, p_contenedor text, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_bodega text := public.wms_bodega_valida(p_bodega);
  v_clave text := public.wms_clave_recepcion(p_asn_id, p_contenedor);
  v_usuario text;
  v_pallets int;
  v_id bigint;
begin
  begin
    v_usuario := public.wms_contexto(p_usuario, 'recepcion_finalizar');
  exception when others then
    if sqlerrm like '%SESION_EXPIRADA%' then raise; end if;
    v_usuario := coalesce(nullif(upper(btrim(p_usuario)), ''), 'APP');
  end;
  select count(distinct lpn) into v_pallets from registro_recepcion r
   where r.bodega = v_bodega and public.wms_clave_recepcion(r.asn_id, r.contenedor) = v_clave;
  if coalesce(v_pallets, 0) = 0 then
    raise exception 'WMS: esta recepción no tiene pallets recibidos todavía';
  end if;
  select id into v_id from wms_reportes_recepcion
   where clave = v_clave and bodega = v_bodega and estado in ('PENDIENTE', 'ENVIANDO') limit 1;
  if v_id is null then
    insert into wms_reportes_recepcion (bodega, clave, asn_id, contenedor, finalizado_por)
    values (v_bodega, v_clave, p_asn_id, nullif(upper(btrim(coalesce(p_contenedor, ''))), ''), v_usuario)
    returning id into v_id;
  end if;
  return jsonb_build_object('reporte_id', v_id, 'pallets', v_pallets,
                            'destinatarios', (select count(*) from wms_destinatarios_reportes where tipo = 'RECEPCION' and activo));
end $$;

-- El PC que envía correos toma un reporte (uno a la vez, sin duplicar entre equipos)
create or replace function public.wms_reporte_tomar(p_equipo text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r record;
begin
  update wms_reportes_recepcion set estado = 'PENDIENTE'
   where estado = 'ENVIANDO' and tomado_en < now() - interval '15 minutes';     -- equipo que se cayó
  -- sin destinatarios activos los reportes esperan en cola (salen solos cuando se agregue alguno)
  if not exists (select 1 from wms_destinatarios_reportes where tipo = 'RECEPCION' and activo) then return null; end if;
  select * into r from wms_reportes_recepcion
   where estado = 'PENDIENTE' or (estado = 'ERROR' and intentos < 5 and tomado_en < now() - interval '10 minutes')
   order by finalizado_en limit 1 for update skip locked;
  if not found then return null; end if;
  update wms_reportes_recepcion set estado = 'ENVIANDO', tomado_por = left(p_equipo, 80), tomado_en = now(),
         intentos = intentos + 1 where id = r.id;
  return to_jsonb(r) || jsonb_build_object(
    'destinatarios', (select coalesce(jsonb_agg(correo order by correo), '[]'::jsonb)
                        from wms_destinatarios_reportes where tipo = 'RECEPCION' and activo),
    'datos', public.wms_recepcion_datos(r.bodega, r.clave));
end $$;

create or replace function public.wms_reporte_marcar(p_id bigint, p_ok boolean, p_error text default null, p_enviado_a text default null)
returns void language sql security definer set search_path = public as $$
  update wms_reportes_recepcion
     set estado = case when p_ok then 'ENVIADO' else 'ERROR' end,
         error = case when p_ok then null else left(p_error, 500) end,
         enviado_en = case when p_ok then now() else enviado_en end,
         enviado_a = coalesce(p_enviado_a, enviado_a)
   where id = p_id;
$$;

-- Datos del reporte de una recepción (cabecera, líneas por SKU/lote y cruce con OC si la tiene)
create or replace function public.wms_recepcion_datos(p_bodega text, p_clave text)
returns jsonb language sql stable security definer set search_path = public as $$
  with r as (
    select * from registro_recepcion
     where bodega = public.wms_bodega_valida(p_bodega) and public.wms_clave_recepcion(asn_id, contenedor) = p_clave
  ), a as (
    select * from asn_cabecera where id = (select max(asn_id) from r)
  )
  select jsonb_build_object(
    'clave', p_clave,
    'contenedor', coalesce((select nullif(btrim(contenedor_referencia), '') from a), (select string_agg(distinct contenedor, ', ') from r)),
    'asn_id', (select id from a), 'numero_oc', (select numero_oc from a), 'proveedor', (select proveedor from a),
    'tiene_oc', exists (select 1 from a),
    'cargada_ns', case when exists (select 1 from a) then public.wms_oc_estado_ns_recepcion((select numero_oc from a)) else 'NO_APLICA' end,
    'inicio', (select min(coalesce(fecha_recepcion, created_at)) from r),
    'fin', (select max(coalesce(fecha_recepcion, created_at)) from r),
    'operadores', (select string_agg(distinct operador, ', ') from r),
    'pallets', (select count(distinct lpn) from r),
    'unidades', (select coalesce(sum(unidades_totales), 0) from r),
    'cajas', (select coalesce(sum(cajas), 0) from r),
    'lineas', coalesce((
      select jsonb_agg(jsonb_build_object('sku', sku, 'lote', lote, 'vencimiento', venc, 'cajas', cajas,
                                          'unidades', unidades, 'pallets', pallets, 'qa', qa) order by sku, lote)
      from (select sku, lote, max(fecha_vencimiento_cl) venc, sum(cajas) cajas, sum(unidades_totales) unidades,
                   count(distinct lpn) pallets, string_agg(distinct estado_pallet, ', ') qa
              from r group by sku, lote) z), '[]'::jsonb),
    'cruce_oc', coalesce((
      select jsonb_agg(jsonb_build_object('sku', d.sku, 'esperado', coalesce(d.unidades_oc, d.unidades_esperadas),
                                          'packing_list', d.unidades_packing_list,
                                          'recibido', (select coalesce(sum(x.unidades_totales), 0) from r x where upper(x.sku) = upper(d.sku)))
                       order by d.sku)
      from asn_detalle d where d.asn_id = (select id from a)), '[]'::jsonb));
$$;

-- ¿Llegó la cita? Por el contenedor escaneado, por el contenedor de la OC/PL o por el número de OC
-- (en el celular las recepciones con OC quedan con contenedor 'PO-<id>').
create or replace function public.wms_cita_llegada(p_bodega text, p_contenedor text, p_numero_oc text, p_fecha date)
returns timestamptz language sql stable security definer set search_path = public as $$
  select min(coalesce(x.fecha_recepcion, x.created_at))
    from registro_recepcion x
    left join asn_cabecera a on a.id = x.asn_id
   where x.bodega = p_bodega
     and coalesce(x.fecha_recepcion, x.created_at) >= p_fecha - 10
     and (upper(replace(coalesce(x.contenedor, ''), ' ', '')) = upper(p_contenedor)
          or upper(replace(coalesce(a.contenedor_referencia, ''), ' ', '')) = upper(p_contenedor)
          or (p_numero_oc is not null and public.wms_numero_oc(a.numero_oc) = public.wms_numero_oc(p_numero_oc)));
$$;

-- ---------------------------------------------------------------------
-- 3. Panel de recepciones
-- ---------------------------------------------------------------------
create or replace function public.wms_panel_recepciones(p_bodega text, p_dias integer default 30)
returns jsonb language sql stable security definer set search_path = public as $$
  with r as (
    select public.wms_clave_recepcion(asn_id, contenedor) clave, *
      from registro_recepcion
     where bodega = public.wms_bodega_valida(p_bodega)
       and coalesce(fecha_recepcion, created_at) > now() - make_interval(days => greatest(coalesce(p_dias, 30), 1))
  ), g as (
    select clave, max(asn_id) asn_id, string_agg(distinct contenedor, ', ') contenedor,
           min(coalesce(fecha_recepcion, created_at)) inicio, max(coalesce(fecha_recepcion, created_at)) fin,
           count(distinct lpn) pallets, sum(unidades_totales) unidades, count(distinct sku) skus,
           string_agg(distinct operador, ', ') operadores
      from r group by clave
  ), recibido as (
    select jsonb_agg(jsonb_build_object(
             'clave', g.clave, 'asn_id', g.asn_id, 'contenedor', coalesce(nullif(btrim(a.contenedor_referencia), ''), g.contenedor), 'inicio', g.inicio, 'fin', g.fin,
             'pallets', g.pallets, 'unidades', g.unidades, 'skus', g.skus, 'operadores', g.operadores,
             'numero_oc', a.numero_oc, 'proveedor', a.proveedor, 'estado_oc_wms', a.estado,
             'tiene_oc', a.id is not null,
             'cargada_ns', case when a.id is null then 'NO_APLICA' else public.wms_oc_estado_ns_recepcion(a.numero_oc) end,
             'recepcion_ns_fecha', n.recepcion_ns_fecha,
             'cita', (select to_char(c.fecha_cita, 'DD-MM-YYYY') || coalesce(' ' || c.hora_cita, '')
                        from wms_agenda_contenedores c
                       where c.estado = 'AGENDADO' and c.bodega = public.wms_bodega_valida(p_bodega)
                         and c.fecha_cita between g.inicio::date - 10 and g.fin::date + 10
                         and (upper(c.contenedor) = any(string_to_array(upper(replace(coalesce(g.contenedor, ''), ' ', '')), ','))
                              or upper(c.contenedor) = upper(replace(coalesce(a.contenedor_referencia, ''), ' ', ''))
                              or (c.numero_oc is not null and c.numero_oc = public.wms_numero_oc(a.numero_oc)))
                       order by c.fecha_cita desc limit 1),
             'reporte', (select jsonb_build_object('estado', x.estado, 'enviado_en', x.enviado_en, 'error', x.error)
                           from wms_reportes_recepcion x where x.clave = g.clave order by x.id desc limit 1))
           order by g.fin desc) j
      from g
      left join asn_cabecera a on a.id = g.asn_id
      left join wms_oc_netsuite n on n.numero_oc = public.wms_numero_oc(a.numero_oc)
  ), esperado as (
    select jsonb_agg(e order by e->>'fecha' nulls last) j from (
      -- Citas agendadas que todavía no llegan
      select jsonb_build_object('tipo', 'CITA', 'documento', c.contenedor, 'numero_oc', c.numero_oc,
                                'proveedor', coalesce(c.proveedor, n.proveedor), 'fecha', c.fecha_cita, 'hora', c.hora_cita,
                                'referencia', c.referencia, 'estado_ns', n.estado_ns, 'id', c.id,
                                'atrasado', c.fecha_cita < (now() at time zone 'America/Santiago')::date) e
        from wms_agenda_contenedores c
        left join wms_oc_netsuite n on n.numero_oc = c.numero_oc
       where c.bodega = public.wms_bodega_valida(p_bodega) and c.estado = 'AGENDADO'
         and c.fecha_cita >= (now() at time zone 'America/Santiago')::date - 30
         and public.wms_cita_llegada(c.bodega, c.contenedor, c.numero_oc, c.fecha_cita) is null
      union all
      -- OC/PL cargados en el WMS sin nada recibido
      select jsonb_build_object('tipo', case when exists (select 1 from asn_detalle d where d.asn_id = a.id and d.unidades_packing_list is not null)
                                             then 'PL' else 'OC' end,
                                'documento', a.codigo_asn, 'numero_oc', a.numero_oc, 'proveedor', a.proveedor,
                                'fecha', coalesce(n.fecha_esperada, a.created_at::date), 'referencia', a.contenedor_referencia,
                                'estado_ns', n.estado_ns, 'asn_id', a.id,
                                'atrasado', n.fecha_esperada < (now() at time zone 'America/Santiago')::date)
        from asn_cabecera a
        left join wms_oc_netsuite n on n.numero_oc = public.wms_numero_oc(a.numero_oc)
       where a.bodega = public.wms_bodega_valida(p_bodega)
         and upper(coalesce(a.estado, '')) not in ('COMPLETADO', 'CERRADO', 'CERRADA', 'ANULADO')
         and not exists (select 1 from registro_recepcion x where x.asn_id = a.id)
      union all
      -- OC de NetSuite pendientes de recibir que el WMS aún no tiene
      select jsonb_build_object('tipo', 'OC_NETSUITE', 'documento', n.tranid, 'numero_oc', n.numero_oc,
                                'proveedor', n.proveedor, 'fecha', n.fecha_esperada, 'estado_ns', n.estado_ns,
                                'ubicacion', n.ubicacion,
                                'atrasado', n.fecha_esperada < (now() at time zone 'America/Santiago')::date)
        from wms_oc_netsuite n
       where upper(coalesce(n.estado_ns, '')) ~ '(PENDIENTE DE RECEP|PENDING RECEIPT|PARCIAL|PARTIAL)'
         and coalesce(n.recepciones_ns, 0) = 0
         and n.fecha_oc > (now() at time zone 'America/Santiago')::date - 180
         and not exists (select 1 from asn_cabecera a where public.wms_numero_oc(a.numero_oc) = n.numero_oc)
    ) z
  )
  select jsonb_build_object('recibido', coalesce((select j from recibido), '[]'::jsonb),
                            'esperado', coalesce((select j from esperado), '[]'::jsonb),
                            'destinatarios', (select count(*) from wms_destinatarios_reportes where tipo = 'RECEPCION' and activo),
                            'reportes_pendientes', (select count(*) from wms_reportes_recepcion where estado in ('PENDIENTE', 'ENVIANDO', 'ERROR')));
$$;

-- Agenda en el calendario
create or replace function public.wms_agenda_rango(p_bodega text, p_desde date, p_hasta date)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', c.id, 'contenedor', c.contenedor, 'fecha_cita', c.fecha_cita, 'hora_cita', c.hora_cita,
           'numero_oc', c.numero_oc, 'referencia', c.referencia, 'proveedor', c.proveedor, 'naviera', c.naviera,
           'observacion', c.observacion, 'estado', c.estado,
           'llego_en', public.wms_cita_llegada(c.bodega, c.contenedor, c.numero_oc, c.fecha_cita))
         order by c.fecha_cita, c.hora_cita), '[]'::jsonb)
  from wms_agenda_contenedores c
  where c.bodega = public.wms_bodega_valida(p_bodega) and c.fecha_cita between p_desde and p_hasta and c.estado <> 'CANCELADO';
$$;

