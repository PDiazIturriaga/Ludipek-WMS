-- ---------------------------------------------------------------------
-- 1. Recepción en NetSuite (Item Receipt) por OC
-- ---------------------------------------------------------------------
alter table public.wms_oc_netsuite add column if not exists recepciones_ns integer;
alter table public.wms_oc_netsuite add column if not exists recepcion_ns_fecha date;
alter table public.wms_oc_netsuite add column if not exists recepcion_ns_revisada_en timestamptz;

create or replace function public.wms_oc_marcar_recepcion_ns(p_filas jsonb)
returns integer language plpgsql security definer set search_path = public as $$
declare
  f jsonb;
  v_n int := 0;
begin
  -- p_filas: [{ns_id, recepciones, fecha}] de las OC revisadas (las que no vienen: 0 recepciones)
  for f in select * from jsonb_array_elements(coalesce(p_filas, '[]'::jsonb)) loop
    update wms_oc_netsuite
       set recepciones_ns = coalesce(nullif(f->>'recepciones', '')::numeric::int, 0),
           recepcion_ns_fecha = nullif(f->>'fecha', '')::date,
           recepcion_ns_revisada_en = now()
     where ns_id = nullif(f->>'ns_id', '')::numeric::bigint;
    v_n := v_n + 1;
  end loop;
  return v_n;
end $$;

-- Estado "cargada en NetSuite" de una OC: SI / PARCIAL / NO / SIN_DATO
create or replace function public.wms_oc_estado_ns_recepcion(p_numero_oc text)
returns text language sql stable security definer set search_path = public as $$
  select case
    when n.numero_oc is null then 'SIN_DATO'
    when coalesce(n.recepciones_ns, 0) > 0 and upper(coalesce(n.estado_ns, '')) ~ '(PARCIAL|PARTIAL)' then 'PARCIAL'
    when coalesce(n.recepciones_ns, 0) > 0 then 'SI'
    when upper(coalesce(n.estado_ns, '')) ~ '(PARCIAL|PARTIAL)' then 'PARCIAL'
    when upper(coalesce(n.estado_ns, '')) ~ '(FACTURA|BILL|CERRAD|CLOSED|RECIBID|RECEIVED)'
         and upper(coalesce(n.estado_ns, '')) !~ '(PENDIENTE DE RECEP|PENDING RECEIPT)' then 'SI'
    when n.recepcion_ns_revisada_en is null and n.recepciones_ns is null then 'SIN_DATO'
    else 'NO' end
  from (select 1) x
  left join wms_oc_netsuite n on n.numero_oc = public.wms_numero_oc(p_numero_oc);
$$;

