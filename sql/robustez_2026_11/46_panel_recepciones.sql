create table if not exists public.wms_agenda_contenedores (
  id          bigint generated by default as identity primary key,
  bodega      text not null default 'Bodega Santiago',
  contenedor  text not null,
  fecha_cita  date not null,
  hora_cita   text,
  numero_oc   text,
  referencia  text,            -- PL, guía, booking...
  proveedor   text,
  naviera     text,
  observacion text,
  estado      text not null default 'AGENDADO' check (estado in ('AGENDADO', 'CANCELADO')),
  origen      text,            -- texto del correo de donde salió
  creado_por  text,
  creado_en   timestamptz not null default now()
);
create unique index if not exists ux_agenda_cont_fecha on public.wms_agenda_contenedores (bodega, upper(contenedor), fecha_cita);
alter table public.wms_agenda_contenedores enable row level security;
revoke all on public.wms_agenda_contenedores from anon, authenticated;
grant select, insert, update, delete on public.wms_agenda_contenedores to service_role;

create or replace function public.wms_agenda_guardar(p_filas jsonb, p_bodega text, p_usuario text default null, p_origen text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  f jsonb;
  v_n int := 0;
  v_cont text;
begin
  for f in select * from jsonb_array_elements(coalesce(p_filas, '[]'::jsonb)) loop
    v_cont := upper(regexp_replace(btrim(coalesce(f->>'contenedor', '')), '\s+', '', 'g'));
    continue when v_cont = '' or nullif(f->>'fecha_cita', '') is null;
    insert into wms_agenda_contenedores (bodega, contenedor, fecha_cita, hora_cita, numero_oc, referencia, proveedor,
                                         naviera, observacion, origen, creado_por)
    values (public.wms_bodega_valida(p_bodega), v_cont, (f->>'fecha_cita')::date, nullif(btrim(f->>'hora_cita'), ''),
            public.wms_numero_oc(f->>'numero_oc'), nullif(btrim(f->>'referencia'), ''), nullif(btrim(f->>'proveedor'), ''),
            nullif(btrim(f->>'naviera'), ''), nullif(btrim(f->>'observacion'), ''), left(p_origen, 4000),
            coalesce(nullif(upper(btrim(p_usuario)), ''), 'PC'))
    on conflict (bodega, upper(contenedor), fecha_cita) do update
      set hora_cita = coalesce(excluded.hora_cita, wms_agenda_contenedores.hora_cita),
          numero_oc = coalesce(excluded.numero_oc, wms_agenda_contenedores.numero_oc),
          referencia = coalesce(excluded.referencia, wms_agenda_contenedores.referencia),
          proveedor = coalesce(excluded.proveedor, wms_agenda_contenedores.proveedor),
          naviera = coalesce(excluded.naviera, wms_agenda_contenedores.naviera),
          observacion = coalesce(excluded.observacion, wms_agenda_contenedores.observacion),
          estado = 'AGENDADO';
    v_n := v_n + 1;
  end loop;
  return jsonb_build_object('guardadas', v_n);
end $$;

create or replace function public.wms_agenda_cancelar(p_id bigint, p_usuario text default null)
returns void language sql security definer set search_path = public as $$
  update wms_agenda_contenedores
     set estado = 'CANCELADO',
         observacion = left(concat_ws(' · ', observacion, 'Cancelada por ' || coalesce(nullif(upper(btrim(p_usuario)), ''), 'PC')), 500)
   where id = p_id;
$$;

