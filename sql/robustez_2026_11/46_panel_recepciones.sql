-- 3) wms_panel_recepciones: lo recibido físicamente con "¿Tiene OC?" y "¿Cargada a NetSuite?",
--    y lo esperado que todavía no llega (OC pendientes en NetSuite, PL cargados, citas agendadas).
-- 4) Reporte de recepción automático: el celular finaliza la recepción del contenedor y queda en
