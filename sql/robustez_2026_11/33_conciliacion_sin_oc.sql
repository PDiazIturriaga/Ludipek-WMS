-- =====================================================================
-- LUDIPEK WMS · 33 CONCILIACIÓN DE RECEPCIONES SIN OC
-- Cuando un contenedor llega antes de que exista la OC, se recibe como "Recepción directa
-- sin OC" (registro_recepcion.asn_id vacío). Cuando la OC se crea, desde el PC
-- (Recepción > Conciliar sin OC) se eligen esos pallets por día y se asignan a la OC.
-- Desde ese momento la OC los muestra en su conciliación (3-way match) como si se hubieran
-- recibido con ella. Queda registro de quién concilió qué, y se puede deshacer mientras
-- la OC no esté cerrada. No mueve stock: solo enlaza el registro de recepción con la OC.
-- =====================================================================
begin;

create table if not exists public.wms_conciliaciones_recepcion (
  id            bigint generated by default as identity primary key,
  asn_id        bigint not null references public.asn_cabecera(id) on delete cascade,
  bodega        text not null,
  registro_ids  bigint[] not null,
  lpns          text[] not null default '{}',
  unidades      integer not null default 0,
  usuario       text,
  comentario    text,
  creado_en     timestamptz not null default now(),
  deshecho_en   timestamptz,
  deshecho_por  text
);
create index if not exists idx_conc_rec_asn on public.wms_conciliaciones_recepcion (asn_id);
alter table public.wms_conciliaciones_recepcion enable row level security;
revoke all on public.wms_conciliaciones_recepcion from anon, authenticated;
grant select, insert, update, delete on public.wms_conciliaciones_recepcion to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Índice para listar rápido lo recibido sin OC
create index if not exists idx_rec_sin_oc on public.registro_recepcion (bodega, fecha_recepcion) where asn_id is null;

-- ---------------------------------------------------------------------
-- Pallets recibidos sin OC en un rango de días (hora de Chile)
-- ---------------------------------------------------------------------
create or replace function public.wms_recepciones_sin_oc(p_bodega text, p_desde date, p_hasta date)
returns table (id bigint, dia date, fecha_hora text, lpn text, sku text, descripcion text, lote text,
               vencimiento text, cajas integer, multiplo integer, unidades integer, contenedor text,
               operador text, estado_pallet text)
language sql stable security definer set search_path = public as $$
  select r.id,
         (coalesce(r.fecha_recepcion, r.created_at) at time zone 'America/Santiago')::date,
         to_char(coalesce(r.fecha_recepcion, r.created_at) at time zone 'America/Santiago', 'DD-MM-YYYY HH24:MI'),
         r.lpn::text, upper(btrim(r.sku))::text, m.descripcion::text, coalesce(r.lote, 'S/L')::text,
         coalesce(r.fecha_vencimiento_cl, to_char(r.fecha_vencimiento, 'DD-MM-YYYY'), '')::text,
         r.cajas, r.multiplo_aplicado, r.unidades_totales,
         nullif(nullif(btrim(r.contenedor), ''), 'SIN-CONTENEDOR'), r.operador::text, r.estado_pallet::text
    from public.registro_recepcion r
    left join public.maestra_sku m on upper(m.sku) = upper(btrim(r.sku))
   where r.asn_id is null
     and coalesce(r.bodega, 'Bodega Santiago') = coalesce(p_bodega, 'Bodega Santiago')
     and coalesce(r.fecha_recepcion, r.created_at) >= (coalesce(p_desde, current_date - 30)::timestamp at time zone 'America/Santiago')
     and coalesce(r.fecha_recepcion, r.created_at) <  ((coalesce(p_hasta, current_date) + 1)::timestamp at time zone 'America/Santiago')
   order by 2, r.lpn, r.sku, r.id
   limit 5000
$$;

-- ---------------------------------------------------------------------
-- Asignar pallets sin OC a una OC
-- ---------------------------------------------------------------------
create or replace function public.wms_conciliar_recepciones(p_asn_id bigint, p_ids bigint[], p_usuario text,
                                                            p_comentario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_asn record;
  v_ids bigint[];
  v_lpns text[];
  v_un integer;
  v_id bigint;
  v_oc text;
  v_ahora text := to_char(now() at time zone 'America/Santiago', 'DD-MM-YYYY HH24:MI');
begin
  select * into v_asn from public.asn_cabecera where id = p_asn_id for update;
  if not found then
    raise exception 'WMS: la OC seleccionada no existe.';
  end if;
  if upper(coalesce(v_asn.estado, '')) like 'COMPLET%' or upper(coalesce(v_asn.estado, '')) like 'CERRAD%' then
    raise exception 'WMS: la OC % ya está cerrada; no se le pueden agregar pallets.', coalesce(v_asn.numero_oc, v_asn.codigo_asn);
  end if;
  if coalesce(cardinality(p_ids), 0) = 0 then
    raise exception 'WMS: no hay pallets seleccionados.';
  end if;

  -- Solo registros que siguen sin OC y son de la misma bodega (bloqueados para evitar dobles asignaciones)
  select array_agg(r.id order by r.id), array_agg(distinct r.lpn::text), coalesce(sum(r.unidades_totales), 0)
    into v_ids, v_lpns, v_un
    from (select * from public.registro_recepcion r
           where r.id = any(p_ids) and r.asn_id is null
             and coalesce(r.bodega, 'Bodega Santiago') = coalesce(v_asn.bodega, 'Bodega Santiago')
           for update) r;

  if coalesce(cardinality(v_ids), 0) = 0 then
    raise exception 'WMS: los pallets seleccionados ya no están pendientes (otra persona los concilió o son de otra bodega).';
  end if;

  v_oc := coalesce(nullif(btrim(v_asn.numero_oc), ''), v_asn.codigo_asn);

  update public.registro_recepcion r
     set asn_id = p_asn_id,
         contenedor = case when coalesce(nullif(btrim(r.contenedor), ''), 'SIN-CONTENEDOR') = 'SIN-CONTENEDOR'
                           then coalesce(nullif(btrim(v_asn.contenedor_referencia), ''), r.contenedor)
                           else r.contenedor end,
         observaciones = btrim(coalesce(r.observaciones, '') || ' [Conciliado a OC ' || v_oc || ' el ' || v_ahora ||
                               ' por ' || coalesce(nullif(btrim(p_usuario), ''), 'PC') || ']')
   where r.id = any(v_ids);

  insert into public.wms_conciliaciones_recepcion (asn_id, bodega, registro_ids, lpns, unidades, usuario, comentario)
  values (p_asn_id, coalesce(v_asn.bodega, 'Bodega Santiago'), v_ids, v_lpns, v_un,
          coalesce(nullif(btrim(p_usuario), ''), 'PC'), nullif(btrim(p_comentario), ''))
  returning id into v_id;

  return jsonb_build_object('conciliacion_id', v_id, 'registros', cardinality(v_ids),
                            'pallets', cardinality(v_lpns), 'unidades', v_un, 'oc', v_oc,
                            'omitidos', cardinality(p_ids) - cardinality(v_ids));
end $$;

-- ---------------------------------------------------------------------
-- Deshacer una conciliación (los pallets vuelven a "sin OC")
-- ---------------------------------------------------------------------
create or replace function public.wms_deshacer_conciliacion(p_id bigint, p_usuario text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_c record;
  v_estado text;
  v_n integer;
begin
  select * into v_c from public.wms_conciliaciones_recepcion where id = p_id for update;
  if not found then
    raise exception 'WMS: la conciliación no existe.';
  end if;
  if v_c.deshecho_en is not null then
    raise exception 'WMS: esa conciliación ya fue deshecha.';
  end if;
  select upper(coalesce(estado, '')) into v_estado from public.asn_cabecera where id = v_c.asn_id;
  if v_estado like 'COMPLET%' or v_estado like 'CERRAD%' then
    raise exception 'WMS: la OC ya está cerrada; no se puede deshacer la conciliación.';
  end if;

  update public.registro_recepcion r
     set asn_id = null,
         observaciones = btrim(coalesce(r.observaciones, '') || ' [Conciliación deshecha el ' ||
                               to_char(now() at time zone 'America/Santiago', 'DD-MM-YYYY HH24:MI') || ' por ' ||
                               coalesce(nullif(btrim(p_usuario), ''), 'PC') || ']')
   where r.id = any(v_c.registro_ids) and r.asn_id = v_c.asn_id;
  get diagnostics v_n = row_count;

  update public.wms_conciliaciones_recepcion
     set deshecho_en = now(), deshecho_por = coalesce(nullif(btrim(p_usuario), ''), 'PC')
   where id = p_id;

  return jsonb_build_object('registros', v_n);
end $$;

revoke all on function public.wms_recepciones_sin_oc(text, date, date) from public, anon, authenticated;
revoke all on function public.wms_conciliar_recepciones(bigint, bigint[], text, text) from public, anon, authenticated;
revoke all on function public.wms_deshacer_conciliacion(bigint, text) from public, anon, authenticated;
grant execute on function public.wms_recepciones_sin_oc(text, date, date) to service_role;
grant execute on function public.wms_conciliar_recepciones(bigint, bigint[], text, text) to service_role;
grant execute on function public.wms_deshacer_conciliacion(bigint, text) to service_role;

commit;

-- Revisión: pallets sin OC de los últimos 30 días
select dia, count(distinct lpn) pallets, sum(unidades) unidades
  from public.wms_recepciones_sin_oc('Bodega Santiago', current_date - 30, current_date)
 group by dia order by dia;
