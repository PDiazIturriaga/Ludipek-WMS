-- =====================================================================
-- LUDIPEK WMS · 03 AUDITORÍA DE STOCK Y KARDEX INMUTABLE  (FASE A)
-- · Todo cambio en bodega_inventario_ubicacion (venga de la app, del PC,
--   del editor de Supabase o de un script) queda registrado con el antes
--   y el después. Ningún movimiento de stock puede quedar sin rastro.
-- · historial_movimientos (kardex) ya no se puede modificar ni borrar.
--   Única excepción: las alertas temporales ALERTA_VACIA_OCUPADA, que la
--   app del celular limpia cuando la ubicación se inventaría.
-- =====================================================================
begin;

create table if not exists public.wms_auditoria_inventario (
  id               bigint generated by default as identity primary key,
  ocurrido_en      timestamptz not null default now(),
  operacion        text not null,           -- INSERT / UPDATE / DELETE
  inventario_id    bigint,
  bodega           text,
  codigo_ubicacion text,
  sku              text,
  lote             text,
  lpn              text,
  unidades_antes   integer,
  unidades_despues integer,
  delta_unidades   integer,
  cajas_antes      integer,
  cajas_despues    integer,
  usuario          text,
  origen           text,                    -- RPC que hizo el cambio o 'DIRECTO'
  rol_db           text,                    -- anon (celular) / service_role (PC) / postgres
  fila_antes       jsonb,
  fila_despues     jsonb
);
create index if not exists idx_aud_inv_sku   on public.wms_auditoria_inventario (sku, ocurrido_en desc);
create index if not exists idx_aud_inv_lpn   on public.wms_auditoria_inventario (lpn, ocurrido_en desc);
create index if not exists idx_aud_inv_fecha on public.wms_auditoria_inventario (ocurrido_en desc);
alter table public.wms_auditoria_inventario enable row level security;
drop policy if exists aud_select on public.wms_auditoria_inventario;
create policy aud_select on public.wms_auditoria_inventario for select to anon, authenticated using (true);

create or replace function public.wms_trg_auditar_inventario()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_old jsonb := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end;
  v_new jsonb := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end;
  v_ref jsonb := coalesce(v_new, v_old);
begin
  -- Cambios que no tocan stock ni ubicación (solo auditor/fecha) no se registran
  if tg_op = 'UPDATE'
     and old.cantidad_unidades is not distinct from new.cantidad_unidades
     and old.cajas is not distinct from new.cajas
     and old.codigo_ubicacion is not distinct from new.codigo_ubicacion
     and old.lote is not distinct from new.lote
     and old.sku is not distinct from new.sku
     and old.lpn is not distinct from new.lpn
     and old.bodega is not distinct from new.bodega then
    return new;
  end if;

  insert into public.wms_auditoria_inventario (
    operacion, inventario_id, bodega, codigo_ubicacion, sku, lote, lpn,
    unidades_antes, unidades_despues, delta_unidades, cajas_antes, cajas_despues,
    usuario, origen, rol_db, fila_antes, fila_despues)
  values (
    tg_op, (v_ref->>'id')::bigint, v_ref->>'bodega', v_ref->>'codigo_ubicacion', v_ref->>'sku', v_ref->>'lote', v_ref->>'lpn',
    (v_old->>'cantidad_unidades')::int, (v_new->>'cantidad_unidades')::int,
    coalesce((v_new->>'cantidad_unidades')::int, 0) - coalesce((v_old->>'cantidad_unidades')::int, 0),
    (v_old->>'cajas')::int, (v_new->>'cajas')::int,
    coalesce(nullif(current_setting('wms.usuario', true), ''), v_new->>'auditor', v_old->>'auditor'),
    coalesce(nullif(current_setting('wms.origen', true), ''), 'DIRECTO'),
    -- rol real de la petición (PostgREST lo informa en el JWT); dentro de una función
    -- SECURITY DEFINER current_user sería el dueño de la función
    coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role',
             nullif(current_setting('role', true), 'none'), session_user),
    v_old, v_new);
  return coalesce(new, old);
end $$;

drop trigger if exists trg_z_auditar_inventario on public.bodega_inventario_ubicacion;
create trigger trg_z_auditar_inventario
  after insert or update or delete on public.bodega_inventario_ubicacion
  for each row execute function public.wms_trg_auditar_inventario();

-- ---------------------------------------------------------------------
-- Kardex inmutable
-- ---------------------------------------------------------------------
create or replace function public.wms_trg_kardex_inmutable()
returns trigger language plpgsql as $$
begin
  if tg_op = 'DELETE' and old.tipo_movimiento = 'ALERTA_VACIA_OCUPADA' then
    return old;
  end if;
  raise exception 'WMS: el historial de movimientos no se puede % (registro %). Registre un movimiento de ajuste en su lugar.',
    lower(tg_op), coalesce(old.id::text, '?');
end $$;

drop trigger if exists trg_kardex_inmutable on public.historial_movimientos;
create trigger trg_kardex_inmutable
  before update or delete on public.historial_movimientos
  for each row execute function public.wms_trg_kardex_inmutable();

-- Permite al celular borrar SOLO alertas temporales (hoy la política no lo permitía)
drop policy if exists rf_delete_alertas on public.historial_movimientos;
create policy rf_delete_alertas on public.historial_movimientos for delete to anon, authenticated
  using (tipo_movimiento = 'ALERTA_VACIA_OCUPADA');

-- ---------------------------------------------------------------------
-- Vista de cuadratura: stock actual vs. suma del kardex de auditoría.
-- Si una fila aparece aquí, alguien cambió stock fuera del registro.
-- ---------------------------------------------------------------------
create or replace view public.v_wms_cuadratura_stock as
with stock as (
  select bodega, sku, sum(cantidad_unidades) as unidades_stock
  from public.bodega_inventario_ubicacion group by bodega, sku
), auditado as (
  select bodega, sku, sum(delta_unidades) as unidades_auditadas,
         min(ocurrido_en) as auditado_desde
  from public.wms_auditoria_inventario group by bodega, sku
)
select coalesce(s.bodega, a.bodega) as bodega, coalesce(s.sku, a.sku) as sku,
       coalesce(s.unidades_stock, 0) as unidades_stock,
       coalesce(a.unidades_auditadas, 0) as movimientos_auditados,
       a.auditado_desde
from stock s full join auditado a on a.bodega = s.bodega and a.sku = s.sku;

commit;
