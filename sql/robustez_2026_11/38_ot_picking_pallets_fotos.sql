create table if not exists public.wms_ot_pallets (
  id         bigint generated by default as identity primary key,
  orden_id   bigint not null references public.netsuite_ordenes_venta(id) on delete cascade,
  numero_ov  text not null,
  bodega     text not null default 'Bodega Santiago',
  lpn        text not null unique,
  estado     text not null default 'ABIERTO' check (estado in ('ABIERTO', 'CERRADO', 'DESPACHADO')),
  usuario    text,
  creado_en  timestamptz not null default now(),
  cerrado_en timestamptz
);
create index if not exists idx_ot_pallets_orden on public.wms_ot_pallets (orden_id, estado);

create table if not exists public.wms_ot_cajas (
  id                   bigint generated by default as identity primary key,
  orden_id             bigint not null references public.netsuite_ordenes_venta(id) on delete cascade,
  numero_ov            text not null,
  id_detalle           bigint not null,
  sku                  text not null,
  lpn                  text not null,
  lote                 text not null default 'S/L',
  fecha_vencimiento_cl text,
  fecha_leida          text,                -- lo que se leyó en la foto (tal como venía)
  unidades             integer not null check (unidades > 0),
  foto_path            text,                -- ruta en el bucket fotos-picking
  ubicacion            text,
  usuario              text,
  bodega               text not null default 'Bodega Santiago',
  creado_en            timestamptz not null default now(),
  anulado_en           timestamptz,
  anulado_motivo       text
);
create index if not exists idx_ot_cajas_orden on public.wms_ot_cajas (orden_id, id_detalle) where anulado_en is null;
create index if not exists idx_ot_cajas_lpn on public.wms_ot_cajas (lpn) where anulado_en is null;

