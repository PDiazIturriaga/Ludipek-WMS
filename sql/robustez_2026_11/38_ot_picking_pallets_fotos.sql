-- =====================================================================
-- Stock en una ubicación de picking que no es la asignada a su SKU
create or replace function public.wms_picking_fuera_de_lugar(p_bodega text, p_filtro text default null)
returns table (id bigint, sku text, descripcion text, marca text, ubicacion_actual text, ubicacion_asignada text,
               lote text, fecha_vencimiento_cl text, unidades integer, cajas integer, lpn text)
language sql stable security definer set search_path = public as $$
  select i.id, upper(i.sku), m.descripcion, m.marca, upper(i.codigo_ubicacion), f.ubicacion,
         i.lote, i.fecha_vencimiento_cl, i.cantidad_unidades, i.cajas, i.lpn
    from bodega_inventario_ubicacion i
    join wms_ubicacion_picking_sku f
      on f.bodega = public.wms_bodega_valida(p_bodega)
     and f.sku = regexp_replace(public.wms_normalizar_sku(i.sku), '-FA$', '')
    left join maestra_sku m on upper(m.sku) = f.sku
   where i.bodega = public.wms_bodega_valida(p_bodega) and i.cantidad_unidades > 0
     and (public.wms_es_ubicacion_picking(i.codigo_ubicacion) or upper(i.codigo_ubicacion) = 'ZONA-PICKING')
     and upper(i.codigo_ubicacion) <> upper(f.ubicacion)
     and coalesce(i.lote, '') not ilike '%|QA:%'
     and (p_filtro is null or btrim(p_filtro) = ''
          or upper(coalesce(m.marca, '')) like '%' || upper(btrim(p_filtro)) || '%'
          or upper(i.sku) like '%' || upper(btrim(p_filtro)) || '%'
          or upper(coalesce(m.descripcion, '')) like '%' || upper(btrim(p_filtro)) || '%')
   order by m.marca nulls last, f.ubicacion, i.sku;
$$;

-- Mover esas filas a la ubicación de picking asignada (con kardex)
create or replace function public.wms_consolidar_picking(p_bodega text, p_ids bigint[], p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r record;
  v_usuario text;
  n int := 0;
  v_un bigint := 0;
begin
  begin
    v_usuario := public.wms_usuario_efectivo(p_usuario);
  exception when others then
    v_usuario := upper(btrim(coalesce(p_usuario, '')));
  end;
  for r in select * from public.wms_picking_fuera_de_lugar(p_bodega, null) x where x.id = any(p_ids) loop
    update bodega_inventario_ubicacion set codigo_ubicacion = r.ubicacion_asignada, updated_at = now()
     where id = r.id and cantidad_unidades > 0;
    insert into historial_movimientos (bodega, usuario, tipo_movimiento, lpn, sku, lote, ubicacion_origen, ubicacion_destino,
                                       cajas_afectadas, unidades_afectadas)
    values (public.wms_bodega_valida(p_bodega), coalesce(nullif(v_usuario, ''), 'PC'), 'CONSOLIDACION_PICKING', r.lpn, r.sku,
            r.lote, r.ubicacion_actual, r.ubicacion_asignada, coalesce(r.cajas, 0), r.unidades);
    n := n + 1;
    v_un := v_un + r.unidades;
  end loop;
  return jsonb_build_object('movidas', n, 'unidades', v_un);
end $$;

