create or replace function public.wms_es_ot_traslado(p_numero text)
returns boolean language sql immutable as $$
  select upper(btrim(coalesce(p_numero, ''))) like 'OT-%';
$$;

-- Pallet abierto de la OT (si no hay, se crea con un LPN nuevo del correlativo de la bodega)
create or replace function public.wms_ot_pallet_abierto(p_orden_id bigint, p_usuario text default null)
returns text language plpgsql security definer set search_path = public as $$
declare
  o record;
  v_lpn text;
  r jsonb;
  v_usuario text;
begin
  select * into o from netsuite_ordenes_venta where id = p_orden_id for update;
  if not found then raise exception 'WMS: la orden % no existe', p_orden_id; end if;
  if not public.wms_es_ot_traslado(o.numero_ov) then
    raise exception 'WMS: % no es una OT de traslado', o.numero_ov;
  end if;
  select lpn into v_lpn from wms_ot_pallets where orden_id = p_orden_id and estado = 'ABIERTO' order by id desc limit 1;
  if v_lpn is not null then return v_lpn; end if;
  begin
    v_usuario := public.wms_usuario_efectivo(p_usuario);
  exception when others then
    v_usuario := upper(btrim(coalesce(p_usuario, '')));
  end;
  r := public.wms_reservar_lpn(coalesce(o.bodega, 'Bodega Santiago'), 1, coalesce(nullif(v_usuario, ''), 'PICKING_OT'));
  v_lpn := 'LPN-' || (r ->> 'desde');
  insert into wms_ot_pallets (orden_id, numero_ov, bodega, lpn, usuario)
  values (p_orden_id, o.numero_ov, coalesce(o.bodega, 'Bodega Santiago'), v_lpn, nullif(v_usuario, ''));
  return v_lpn;
end $$;

-- Estado de la OT para el celular: pallet abierto y pallets con su contenido
create or replace function public.wms_ot_estado(p_orden_id bigint, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_lpn text := public.wms_ot_pallet_abierto(p_orden_id, p_usuario);
begin
  return jsonb_build_object(
    'lpn_abierto', v_lpn,
    'pallets', coalesce((
      select jsonb_agg(jsonb_build_object(
               'lpn', p.lpn, 'estado', p.estado,
               'cajas', (select count(*) from wms_ot_cajas c where c.lpn = p.lpn and c.anulado_en is null),
               'unidades', (select coalesce(sum(c.unidades), 0) from wms_ot_cajas c where c.lpn = p.lpn and c.anulado_en is null),
               'lineas', coalesce((select jsonb_agg(jsonb_build_object('sku', z.sku, 'lote', z.lote,
                                                     'fecha_vencimiento_cl', z.venc, 'unidades_totales', z.un, 'cajas', z.n) order by z.sku)
                                    from (select c.sku, c.lote, c.fecha_vencimiento_cl venc, sum(c.unidades) un, count(*) n
                                            from wms_ot_cajas c where c.lpn = p.lpn and c.anulado_en is null
                                           group by 1, 2, 3) z), '[]'::jsonb))
             order by p.id)
        from wms_ot_pallets p where p.orden_id = p_orden_id), '[]'::jsonb));
end $$;

-- Una caja (o varias del mismo lote) pickeada, con su foto, al pallet abierto
create or replace function public.wms_ot_registrar_caja(
  p_orden_id bigint, p_id_detalle bigint, p_lote text, p_vencimiento text, p_unidades integer,
  p_fecha_leida text default null, p_foto_path text default null, p_ubicacion text default null,
  p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  o record;
  d record;
  v_lpn text;
  v_id bigint;
  v_usuario text;
begin
  select * into o from netsuite_ordenes_venta where id = p_orden_id;
  if not found then raise exception 'WMS: la orden % no existe', p_orden_id; end if;
  select * into d from netsuite_detalle_ov where id = p_id_detalle and orden_id = p_orden_id;
  if not found then raise exception 'WMS: la línea % no es de la orden %', p_id_detalle, o.numero_ov; end if;
  if coalesce(p_unidades, 0) <= 0 then raise exception 'WMS: unidades inválidas'; end if;
  begin
    v_usuario := public.wms_usuario_efectivo(p_usuario);
  exception when others then
    v_usuario := upper(btrim(coalesce(p_usuario, '')));
  end;
  v_lpn := public.wms_ot_pallet_abierto(p_orden_id, p_usuario);
  insert into wms_ot_cajas (orden_id, numero_ov, id_detalle, sku, lpn, lote, fecha_vencimiento_cl, fecha_leida, unidades,
                            foto_path, ubicacion, usuario, bodega)
  values (p_orden_id, o.numero_ov, p_id_detalle, upper(d.sku), v_lpn,
          coalesce(nullif(upper(btrim(p_lote)), ''), 'S/L'), nullif(btrim(coalesce(p_vencimiento, '')), ''),
          left(nullif(btrim(coalesce(p_fecha_leida, '')), ''), 40), p_unidades,
          left(nullif(btrim(coalesce(p_foto_path, '')), ''), 300), upper(nullif(btrim(coalesce(p_ubicacion, '')), '')),
          nullif(v_usuario, ''), coalesce(o.bodega, 'Bodega Santiago'))
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'lpn', v_lpn);
end $$;

-- Deshacer la última caja de una línea (si el operador se equivocó)
create or replace function public.wms_ot_anular_caja(p_id bigint, p_motivo text default null, p_usuario text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  update wms_ot_cajas set anulado_en = now(),
         anulado_motivo = left(coalesce(nullif(btrim(p_motivo), ''), 'Anulada por ' || coalesce(p_usuario, 'APP')), 200)
   where id = p_id and anulado_en is null
     and exists (select 1 from wms_ot_pallets p where p.lpn = wms_ot_cajas.lpn and p.estado = 'ABIERTO');
end $$;

-- Cerrar el pallet abierto y abrir otro (devuelve el contenido del cerrado para imprimir)
create or replace function public.wms_ot_cerrar_pallet(p_orden_id bigint, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_lpn text;
  v_nuevo text;
  v_est jsonb;
begin
  select lpn into v_lpn from wms_ot_pallets where orden_id = p_orden_id and estado = 'ABIERTO' order by id desc limit 1;
  if v_lpn is null or not exists (select 1 from wms_ot_cajas where lpn = v_lpn and anulado_en is null) then
    raise exception 'WMS: el pallet actual está vacío; pickee al menos una caja antes de cerrarlo.';
  end if;
  update wms_ot_pallets set estado = 'CERRADO', cerrado_en = now() where lpn = v_lpn;
  v_nuevo := public.wms_ot_pallet_abierto(p_orden_id, p_usuario);
  v_est := public.wms_ot_estado(p_orden_id, p_usuario);
  return jsonb_build_object('lpn_cerrado', v_lpn, 'lpn_nuevo', v_nuevo,
                            'pallet', (select x from jsonb_array_elements(v_est -> 'pallets') x where x ->> 'lpn' = v_lpn));
end $$;

-- Cerrar el picking de la OT: lo pickeado queda consolidado por LPN y la OT pasa a EN_TRANSITO_CCP
create or replace function public.wms_cerrar_picking_ot(p_orden_id bigint, p_lineas jsonb, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  o record;
  d record;
  m record;
  v_ultimo text;
  v_suma int;
  v_falta int;
  v_detalle jsonb;
  v_pallets int;
  v_peso numeric := 0;
  v_res jsonb;
  v_usr text := coalesce(nullif(upper(btrim(p_usuario)), ''), 'PICKING_OT');
begin
  select * into o from netsuite_ordenes_venta where id = p_orden_id;
  if not found then raise exception 'WMS: la orden % no existe', p_orden_id; end if;
  if not public.wms_es_ot_traslado(o.numero_ov) then
    raise exception 'WMS: % no es una OT de traslado', o.numero_ov;
  end if;

  -- a) Guardar lo pickeado (misma validación de siempre)
  perform public.wms_cerrar_picking(p_orden_id, p_lineas, p_usuario, null);

  -- b) Cuadrar cajas con lo pickeado: lo pickeado manda
  select lpn into v_ultimo from wms_ot_pallets where orden_id = p_orden_id order by id desc limit 1;
  for d in select * from netsuite_detalle_ov where orden_id = p_orden_id order by id loop
    select coalesce(sum(unidades), 0) into v_suma from wms_ot_cajas where id_detalle = d.id and anulado_en is null;
    -- más cajas que lo pickeado: se anulan las últimas
    while v_suma > coalesce(d.cantidad_pickeada, 0) loop
      update wms_ot_cajas set anulado_en = now(), anulado_motivo = 'Ajuste al cerrar: más cajas que lo pickeado'
       where id = (select id from wms_ot_cajas where id_detalle = d.id and anulado_en is null order by id desc limit 1);
      select coalesce(sum(unidades), 0) into v_suma from wms_ot_cajas where id_detalle = d.id and anulado_en is null;
    end loop;
    -- menos cajas que lo pickeado (picks sin foto o de una app anterior): el resto va al último pallet
    v_falta := coalesce(d.cantidad_pickeada, 0) - v_suma;
    if v_falta > 0 then
      if v_ultimo is null then
        v_ultimo := public.wms_ot_pallet_abierto(p_orden_id, p_usuario);
      end if;
      for m in
        select btrim(split_part(x[1], ' / ', 1)) lote, btrim(split_part(x[1], ' / ', 2)) venc, x[2]::int un
          from regexp_matches(coalesce(d.lotes_pickeados, ''), '\s*([^|]+?)\s*\((\d+) UN\)', 'g') x
      loop
        exit when v_falta <= 0;
        insert into wms_ot_cajas (orden_id, numero_ov, id_detalle, sku, lpn, lote, fecha_vencimiento_cl, unidades, usuario, bodega)
        values (p_orden_id, o.numero_ov, d.id, upper(d.sku), v_ultimo,
                coalesce(nullif(regexp_replace(m.lote, '^\[[^\]]*\]\s*', ''), ''), 'S/L'), nullif(m.venc, ''),
                least(m.un, v_falta), v_usr, coalesce(o.bodega, 'Bodega Santiago'));
        v_falta := v_falta - least(m.un, v_falta);
      end loop;
      if v_falta > 0 then
        insert into wms_ot_cajas (orden_id, numero_ov, id_detalle, sku, lpn, lote, unidades, usuario, bodega)
        values (p_orden_id, o.numero_ov, d.id, upper(d.sku), v_ultimo, 'S/L', v_falta, v_usr, coalesce(o.bodega, 'Bodega Santiago'));
      end if;
    end if;
    if coalesce(d.cantidad_pickeada, 0) > 0 then
      select v_peso + d.cantidad_pickeada * coalesce(ms.peso_kg, ms.peso_gr / 1000.0, 0) into v_peso
        from maestra_sku ms where upper(ms.sku) = upper(public.wms_normalizar_sku(d.sku)) limit 1;
    end if;
  end loop;

  -- c) Pallets vacíos fuera; los demás quedan cerrados
  delete from wms_ot_pallets p where p.orden_id = p_orden_id
     and not exists (select 1 from wms_ot_cajas c where c.lpn = p.lpn and c.anulado_en is null);
  update wms_ot_pallets set estado = 'CERRADO', cerrado_en = coalesce(cerrado_en, now())
   where orden_id = p_orden_id and estado = 'ABIERTO';

  select jsonb_agg(jsonb_build_object('id_detalle', z.id_detalle, 'sku', z.sku, 'lote', z.lote,
                                      'fecha_vencimiento_cl', z.venc, 'unidades_totales', z.un, 'cajas', z.n,
                                      'lpn_pallet', z.lpn, 'lpn_consolidado', z.lpn) order by z.lpn, z.sku),
         count(distinct z.lpn)
    into v_detalle, v_pallets
    from (select c.id_detalle, c.sku, c.lote, c.fecha_vencimiento_cl venc, c.lpn, sum(c.unidades) un, count(*) n
            from wms_ot_cajas c where c.orden_id = p_orden_id and c.anulado_en is null
           group by 1, 2, 3, 4, 5) z;
  if coalesce(v_pallets, 0) = 0 then
    raise exception 'WMS: la OT % no tiene nada pickeado', o.numero_ov;
  end if;

  -- d) Cierre igual que el packing por pallets: consolidado por LPN y EN_TRANSITO_CCP
  v_res := public.wms_cerrar_packing(p_orden_id, 'PALLETS', v_detalle, v_pallets, 'PALLET', null,
                                     (select min(lpn) from wms_ot_pallets where orden_id = p_orden_id),
                                     nullif(round(v_peso, 2), 0), null, null, v_usr, null);
  return v_res || jsonb_build_object('sin_packing', true,
                                     'pallets', (public.wms_ot_estado_sin_abrir(p_orden_id)));
end $$;

-- Igual que wms_ot_estado pero sin abrir un pallet nuevo (para después del cierre)
create or replace function public.wms_ot_estado_sin_abrir(p_orden_id bigint)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'lpn', p.lpn, 'estado', p.estado,
           'cajas', (select count(*) from wms_ot_cajas c where c.lpn = p.lpn and c.anulado_en is null),
           'unidades', (select coalesce(sum(c.unidades), 0) from wms_ot_cajas c where c.lpn = p.lpn and c.anulado_en is null),
           'lineas', coalesce((select jsonb_agg(jsonb_build_object('sku', z.sku, 'lote', z.lote, 'fecha_vencimiento_cl', z.venc,
                                                                   'unidades_totales', z.un, 'cajas', z.n) order by z.sku)
                                from (select c.sku, c.lote, c.fecha_vencimiento_cl venc, sum(c.unidades) un, count(*) n
                                        from wms_ot_cajas c where c.lpn = p.lpn and c.anulado_en is null group by 1, 2, 3) z), '[]'::jsonb))
         order by p.id), '[]'::jsonb)
    from wms_ot_pallets p where p.orden_id = p_orden_id;
$$;

