-- =====================================================================
-- B) Ubicaciones de picking bloqueadas: volver a habilitarlas
-- =====================================================================
-- (en una sola instrucción: el SQL Editor de Supabase no conserva tablas temporales entre instrucciones)
with desbloqueadas as (
  update public.bodega_ubicaciones u
     set estado = 'Habilitada', estado_ubicacion = 'DISPONIBLE'
   where public.wms_es_ubicacion_picking(u.codigo_ubicacion)
     and (coalesce(u.estado, '') ilike 'bloq%' or coalesce(u.estado_ubicacion, '') ilike 'bloq%')
  returning u.bodega, u.codigo_ubicacion
)
select 'Ubicaciones de picking desbloqueadas' as que, count(*) as cantidad,
       string_agg(codigo_ubicacion, ', ' order by codigo_ubicacion) as cuales
  from desbloqueadas;

