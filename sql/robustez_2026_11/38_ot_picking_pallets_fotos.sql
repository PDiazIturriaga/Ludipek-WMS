-- =====================================================================
-- LUDIPEK WMS · 38 OT A CONCEPCIÓN: FOTO DE LA FECHA Y PALLET LPN EN EL PICKING
--                  + UBICACIONES DE PICKING VISIBLES Y CONSOLIDACIÓN DE PICKING
-- (requiere 11, 12, 19, 27 y 37)
--
-- A) OT de traslado (OT-...) sin packing:
--    · Al pickear cada caja se toma la FOTO DE LA FECHA. La foto queda guardada en Supabase
--      Storage (bucket "fotos-picking") y su registro en wms_ot_cajas: OT, SKU, lote, fecha leída,
--      unidades, pallet y usuario.
--    · El picking arma el pallet de una vez: al abrir la OT se genera un LPN real (correlativo de
--      Bodega Santiago, el mismo de las etiquetas LPN) y cada caja queda en ese pallet. "Cerrar
--      pallet" lo deja listo e imprime su contenido; se abre otro con un LPN nuevo.
--    · Al cerrar el picking la OT queda consolidada por LPN y pasa a EN_TRANSITO_CCP (igual que al
--      cerrar su packing), lista para que Concepción la reciba por LPN.
-- B) Ubicaciones de picking (nivel 01) bloqueadas: se desbloquean para que el sistema las use
--    (picking fijo, almacenamiento dirigido, movimiento a picking).
-- C) Consolidación de picking: stock que está en una ubicación de picking que NO es la asignada
--    al SKU se puede mover a su ubicación de picking actual (PC: Mov. Stock > Consolidar picking).
-- =====================================================================
begin;

