-- =====================================================================
-- LUDIPEK WMS · 17 CORREGIR STOCK CON UNIDADES = CAJAS  (requiere 04 y 15)   [versión 2]
-- Problema: filas de stock con "85 Cj (85 UN)" en productos que vienen en cajas
-- de 48 (ej. USA603, LPN-100450).
-- La maestra tiene una fila por presentación (UN = 1, display = 6, caja = 48...):
-- las unidades por caja son el MAYOR múltiplo del SKU, o el de la recepción del LPN.
-- Este script:
--   1) wms_multiplo_sku(): unidades por caja confiables (recepción del LPN >
--      mayor múltiplo de la maestra > lo que más se ha recibido del SKU).
--   2) Si la versión anterior de este script alcanzó a cambiar la maestra
--      (filas UN de múltiplo 1 pasadas a 48), las devuelve a 1.
--   3) Corrige el stock con unidades = cajas: unidades = cajas x múltiplo.
--      Respaldo en wms_respaldo_unidades_cajas y kardex CORRECCION_UNIDADES_CAJA.
--   4) El conteo cíclico usa wms_multiplo_sku() desde ahora.
-- Todo el arreglo de datos va en un solo bloque (todo o nada). Al final muestra lo corregido.
-- Revisar antes (solo lectura): 17b_revisar_unidades_cajas.sql
-- =====================================================================

-- 1) Múltiplo confiable -----------------------------------------------------
create or replace function public.wms_multiplo_sku(p_sku text, p_bodega text default null, p_lpn text default null)
returns integer language sql stable security definer set search_path = public as $$
  select greatest(coalesce(
    (select max(r.multiplo_aplicado) from registro_recepcion r
      where nullif(btrim(coalesce(p_lpn, '')), '') is not null and r.lpn = upper(btrim(p_lpn)) and r.sku = p_sku
        and (p_bodega is null or r.bodega = p_bodega) and r.multiplo_aplicado > 1),
    (select max(m.multiplo) from maestra_sku m where m.sku = p_sku and m.multiplo > 1),
    (select r.multiplo_aplicado from registro_recepcion r where r.sku = p_sku and r.multiplo_aplicado > 1
      group by r.multiplo_aplicado order by count(*) desc, max(r.fecha_recepcion) desc limit 1),
    1), 1);
$$;
grant execute on function public.wms_multiplo_sku(text, text, text) to anon, authenticated, service_role;

create table if not exists public.wms_respaldo_unidades_cajas (
  id             bigint generated by default as identity primary key,
  tipo           text not null,            -- 'INVENTARIO' (o 'MAESTRA' de la versión anterior)
  referencia_id  bigint,
  sku            text,
  lpn            text,
  ubicacion      text,
  cajas          integer,
  antes          integer,
  despues        integer,
  multiplo       integer,
  fuente         text,
  creado_en      timestamptz not null default now()
);
alter table public.wms_respaldo_unidades_cajas enable row level security;

-- 2) y 3) Arreglo de datos en un solo bloque -------------------------------
do $$
declare
  r record;
  v_mult int;
  v_fuente text;
  v_rev int := 0;
  v_n int := 0;
begin
  perform public.wms_contexto('SISTEMA', 'correccion_unidades_cajas');

  -- 2) Deshacer el cambio de maestra de la versión anterior (si alcanzó a quedar)
  for r in select id, sku, despues from wms_respaldo_unidades_cajas where tipo = 'MAESTRA' loop
    update maestra_sku
       set multiplo = 1
     where sku = r.sku and multiplo = r.despues
       and upper(btrim(coalesce(unidad_medida, ''))) in ('UN', 'UND', 'UNI', 'UNID', 'UNIDAD', 'UNIDADES', 'U', 'C/U', 'EA');
    get diagnostics v_n = row_count;
    v_rev := v_rev + v_n;
    update wms_respaldo_unidades_cajas set tipo = 'MAESTRA_REVERTIDA' where id = r.id;
  end loop;
  if v_rev > 0 then
    raise notice 'Maestra: % fila(s) de unidad devueltas a múltiplo 1', v_rev;
  end if;

  -- 3) Stock con unidades = cajas
  for r in select * from bodega_inventario_ubicacion i
            where i.cajas > 0 and i.cantidad_unidades = i.cajas
            order by i.id for update loop
    v_mult := public.wms_multiplo_sku(r.sku, r.bodega, r.lpn);
    continue when v_mult <= 1;
    v_fuente := case when exists (select 1 from registro_recepcion x where x.bodega = r.bodega and x.lpn = r.lpn
                                    and x.sku = r.sku and x.multiplo_aplicado > 1)
                     then 'RECEPCION DEL LPN' else 'MAESTRA (CAJA) / RECEPCIONES DEL SKU' end;
    update bodega_inventario_ubicacion set cantidad_unidades = r.cajas * v_mult where id = r.id;
    insert into wms_respaldo_unidades_cajas (tipo, referencia_id, sku, lpn, ubicacion, cajas, antes, despues, multiplo, fuente)
    values ('INVENTARIO', r.id, r.sku, r.lpn, r.codigo_ubicacion, r.cajas, r.cantidad_unidades, r.cajas * v_mult, v_mult, v_fuente);
    perform public.wms_kardex(r.bodega, 'CORRECCION_UNIDADES_CAJA', r.lpn, r.sku, r.lote, r.codigo_ubicacion,
                              'CAJA DE ' || v_mult || ' UN', 0, r.cajas * v_mult - r.cantidad_unidades);
  end loop;
end $$;

-- 4) Conteo cíclico con el múltiplo confiable --------------------------------
create or replace function public.wms_registrar_conteo(
  p_bodega text, p_ubicacion text, p_sku text, p_lote text, p_vencimiento text,
  p_lpn text, p_cajas integer, p_modo text default 'SUMAR',
  p_inventario_id bigint default null, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_bodega text := public.wms_bodega_valida(p_bodega);
  v_usuario text := public.wms_contexto(p_usuario, 'wms_registrar_conteo');
  v_ubic text;
  v_sku text := public.wms_normalizar_sku(p_sku);
  v_lote text := public.wms_normalizar_lote(p_lote);
  v_lpn text := nullif(upper(btrim(coalesce(p_lpn, ''))), '');
  v_venc date := public.wms_fecha_desde_texto(p_vencimiento);
  v_mult int;
  v_unid int;
  v_modo text := upper(coalesce(p_modo, 'SUMAR'));
  o record;
  v_cajas_ant int := 0;
  v_unid_ant int := 0;
  v_cajas_fin int;
  v_unid_fin int;
  v_tipo text;
begin
  if v_sku = '' then raise exception 'WMS: falta el SKU'; end if;
  if coalesce(p_cajas, -1) < 0 then raise exception 'WMS: la cantidad contada no es válida'; end if;
  if coalesce(btrim(p_vencimiento), '') not in ('', 'S/F') and v_venc is null then
    raise exception 'WMS: vencimiento inválido "%". Use DD-MM-YYYY', p_vencimiento;
  end if;
  if v_modo not in ('SUMAR', 'FIJAR') then raise exception 'WMS: modo de conteo inválido %', p_modo; end if;
  v_ubic := public.wms_ubicacion_valida(v_bodega, p_ubicacion);
  -- Unidades por caja: recepción de ese LPN > caja de la maestra (mayor múltiplo) > lo más recibido del SKU
  v_mult := public.wms_multiplo_sku(v_sku, v_bodega, v_lpn);
  v_unid := p_cajas * v_mult;

  if p_inventario_id is not null then
    select * into o from bodega_inventario_ubicacion where id = p_inventario_id for update;
    if not found then raise exception 'WMS: la línea de inventario % ya no existe', p_inventario_id; end if;
    v_modo := 'FIJAR';
  else
    perform pg_advisory_xact_lock(hashtext('INV|' || v_bodega || '|' || v_ubic || '|' || v_sku || '|' || v_lote || '|' || coalesce(v_lpn, '')));
    select * into o from bodega_inventario_ubicacion
     where bodega = v_bodega and codigo_ubicacion = v_ubic and sku = v_sku and lote = v_lote and lpn is not distinct from v_lpn
     order by id limit 1 for update;
  end if;

  if found then
    v_cajas_ant := coalesce(o.cajas, 0);
    v_unid_ant := o.cantidad_unidades;
  end if;
  v_cajas_fin := case when v_modo = 'SUMAR' then v_cajas_ant + p_cajas else p_cajas end;
  v_unid_fin  := case when v_modo = 'SUMAR' then v_unid_ant + v_unid else v_unid end;

  if o.id is not null then
    if v_unid_fin <= 0 then
      delete from bodega_inventario_ubicacion where id = o.id;
    else
      update bodega_inventario_ubicacion
         set codigo_ubicacion = v_ubic, lote = v_lote, lpn = v_lpn, sku = v_sku,
             fecha_vencimiento_cl = coalesce(public.wms_fecha_cl(v_venc), fecha_vencimiento_cl),
             cajas = v_cajas_fin, cantidad_unidades = v_unid_fin, auditor = v_usuario, fecha = now()::text
       where id = o.id;
    end if;
  elsif v_unid_fin > 0 then
    perform public.wms_sumar_en_ubicacion(v_bodega, v_ubic, v_sku, v_lote, v_lpn, public.wms_fecha_cl(v_venc), v_cajas_fin, v_unid_fin);
  else
    return jsonb_build_object('sin_cambios', true, 'mensaje', 'Cantidad 0 en una ubicación sin stock: no se registró nada.');
  end if;

  v_tipo := case when p_inventario_id is not null then 'AJUSTE_CICLICO_MODIFICACION'
                 when v_unid_fin - v_unid_ant >= 0 then 'AJUSTE_CICLICO_SUMA' else 'AJUSTE_CICLICO_RESTA' end;
  if v_unid_fin <> v_unid_ant or v_cajas_fin <> v_cajas_ant then
    perform public.wms_kardex(v_bodega, v_tipo, v_lpn, v_sku, v_lote, coalesce(o.codigo_ubicacion, v_ubic), v_ubic,
                              v_cajas_fin - v_cajas_ant, v_unid_fin - v_unid_ant);
  end if;

  return jsonb_build_object('ubicacion', v_ubic, 'sku', v_sku, 'lote', v_lote, 'multiplo', v_mult,
                            'cajas_antes', v_cajas_ant, 'cajas_despues', v_cajas_fin,
                            'unidades_antes', v_unid_ant, 'unidades_despues', v_unid_fin);
end $$;

grant execute on function public.wms_registrar_conteo(text, text, text, text, text, text, integer, text, bigint, text)
  to anon, authenticated, service_role;

-- Resultado: lo corregido en esta ejecución
select ubicacion, lpn, sku, cajas, antes as unidades_antes, despues as unidades_despues,
       multiplo as unidades_por_caja, fuente
from public.wms_respaldo_unidades_cajas
where tipo = 'INVENTARIO' and creado_en > now() - interval '10 minutes'
order by sku, ubicacion, lpn;
