do $$ begin
  if to_regclass('public.wms_modulos_app') is not null then
    insert into public.wms_modulos_app (codigo, plataforma, nombre, descripcion, orden, indice_app, reemplaza) values
      ('APP_DESPACHO_EXPORT', 'RF', 'Despacho exportación', 'Escanear LPN de un despacho (ej. Perú)', 63, 14, '{RF_PICKING}'),
      ('PC_DESPACHOS',        'PC', 'Despachos de exportación', null, 46, null, '{}')
    on conflict (codigo) do update
      set plataforma = excluded.plataforma, nombre = excluded.nombre, descripcion = excluded.descripcion,
          orden = excluded.orden, indice_app = excluded.indice_app, reemplaza = excluded.reemplaza;
  end if;
  update public.wms_usuarios u
     set modulos_rf = (select array(select distinct x from unnest(u.modulos_rf || array['APP_DESPACHO_EXPORT']) x order by x))
   where 'APP_CARGA_CAMION' = any(u.modulos_rf) and not ('APP_DESPACHO_EXPORT' = any(u.modulos_rf));
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'wms_usuarios' and column_name = 'modulos_pc') then
    execute $q$
      update public.wms_usuarios u
         set modulos_pc = (select array(select distinct x from unnest(u.modulos_pc || array['PC_DESPACHOS']) x order by x))
       where 'PC_CARGAS' = any(u.modulos_pc) and not ('PC_DESPACHOS' = any(u.modulos_pc))$q$;
  end if;
exception when others then
  raise notice 'permisos de despacho no actualizados: %', sqlerrm;
end $$;

