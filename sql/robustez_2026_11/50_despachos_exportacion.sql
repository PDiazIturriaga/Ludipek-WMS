-- =====================================================================
-- LUDIPEK WMS · 50 DESPACHOS DE EXPORTACIÓN (ej. traslado Chile → Perú)
--
-- 1) En el PC se crea el despacho (destino, referencia, contenedor) y se carga el pedido desde el
--    Excel (SKU y unidades; pallets opcionales).
-- 2) En el celular (módulo 14) o en el PC se escanea cada LPN que sube: el WMS lee su contenido del
--    stock (SKU, lote, vencimiento, unidades) y calcula cajas, displays y unidades con la maestra.
-- 3) El avance se ve por SKU contra el pedido (pallets, cajas, displays, unidades, lotes y fechas).
-- 4) Al cerrar se puede descontar el stock (queda en el kardex como DESPACHO_EXPORTACION y una copia
--    de cada fila en el despacho) y se exporta el packing list.
-- Se puede ejecutar más de una vez.
-- =====================================================================
begin;

create table if not exists public.wms_despachos (
  id               bigint generated by default as identity primary key,
  numero           text not null unique,
  bodega           text not null,
  destino          text not null default 'PERÚ',
  referencia       text,
  contenedor       text,
  nota             text,
  estado           text not null default 'ABIERTO',      -- ABIERTO / CERRADO / ANULADO
  stock_descontado boolean not null default false,
  creado_por       text,
  creado_en        timestamptz not null default now(),
  cerrado_por      text,
  cerrado_en       timestamptz
);
create table if not exists public.wms_despacho_pedido (
  id            bigint generated by default as identity primary key,
  despacho_id   bigint not null references public.wms_despachos(id) on delete cascade,
  sku           text not null,
  descripcion   text,
  unidades      integer not null default 0,
  pallets       numeric,
  unique (despacho_id, sku)
);
create table if not exists public.wms_despacho_lpn (
  id            bigint generated by default as identity primary key,
  despacho_id   bigint not null references public.wms_despachos(id) on delete cascade,
  lpn           text not null,
  ubicacion     text,
  filas         jsonb not null default '[]'::jsonb,        -- contenido del LPN al escanearlo
  descontado    jsonb,                                      -- lo que se descontó del stock al cerrar
  escaneado_por text,
  escaneado_en  timestamptz not null default now(),
  unique (despacho_id, lpn)
);
create index if not exists ix_despacho_lpn_lpn on public.wms_despacho_lpn (lpn);

alter table public.wms_despachos enable row level security;
alter table public.wms_despacho_pedido enable row level security;
alter table public.wms_despacho_lpn enable row level security;
revoke all on public.wms_despachos, public.wms_despacho_pedido, public.wms_despacho_lpn from anon, authenticated;
grant select, insert, update, delete on public.wms_despachos, public.wms_despacho_pedido, public.wms_despacho_lpn to service_role;

-- ---------------------------------------------------------------------
-- Empaque por SKU (la maestra puede tener filas UNIDAD, DISPLAY y CAJA)
-- ---------------------------------------------------------------------
create or replace function public.wms_empaque_sku(p_sku text)
returns table (multiplo_caja integer, multiplo_display integer, peso_unidad_kg numeric, descripcion text)
language sql stable security definer set search_path = public as $$
  with m as (
    select upper(replace(coalesce(unidad_medida, ''), ' ', '_')) um, multiplo, descripcion,
           coalesce(peso_kg, peso_gr / 1000.0) peso
      from maestra_sku where upper(btrim(sku)) = upper(btrim(p_sku)) and activo is distinct from false
  )
  select greatest(1, coalesce(max(multiplo) filter (where um in ('CAJA', 'CAJA_MASTER', 'MASTER', 'CJ')), max(multiplo), 1))::int,
         greatest(1, coalesce(max(multiplo) filter (where um in ('DISPLAY', 'DSP')), 1))::int,
         coalesce(max(peso) filter (where um in ('UN', 'UNIDAD', 'UNIT') and peso > 0),
                  max(peso / nullif(multiplo, 0)) filter (where um in ('CAJA', 'CAJA_MASTER', 'MASTER', 'CJ') and peso > 0)),
         max(descripcion) filter (where nullif(btrim(descripcion), '') is not null and descripcion <> 'DESC')
    from m;
$$;

-- unidades -> {cajas, displays, sueltas}
create or replace function public.wms_empaque_desglose(p_unidades integer, p_caja integer, p_display integer)
returns jsonb language sql immutable as $$
  select jsonb_build_object(
    'cajas', coalesce(p_unidades, 0) / greatest(1, p_caja),
    'displays', case when coalesce(p_display, 1) > 1 and p_display < greatest(1, p_caja)
                     then (coalesce(p_unidades, 0) % greatest(1, p_caja)) / p_display else 0 end,
    'sueltas', case when coalesce(p_display, 1) > 1 and p_display < greatest(1, p_caja)
                    then (coalesce(p_unidades, 0) % greatest(1, p_caja)) % p_display
                    else coalesce(p_unidades, 0) % greatest(1, p_caja) end);
$$;

create or replace function public.wms_usuario_despacho(p_usuario text)
returns text language plpgsql security definer set search_path = public as $$
begin
  return public.wms_contexto(p_usuario, 'despacho_exportacion');
exception when others then
  if sqlerrm like '%SESION_EXPIRADA%' then raise; end if;
  return coalesce(nullif(upper(btrim(coalesce(p_usuario, ''))), ''), 'APP');
end $$;

-- ---------------------------------------------------------------------
-- Detalle completo del despacho
-- ---------------------------------------------------------------------
create or replace function public.wms_despacho_detalle(p_id bigint)
returns jsonb language sql stable security definer set search_path = public as $$
  with d as (select * from wms_despachos where id = p_id),
  filas as (   -- cada fila de stock escaneada (sku, lote, vencimiento, unidades) con su LPN
    select l.lpn, l.ubicacion, upper(btrim(f->>'sku')) sku, coalesce(nullif(btrim(f->>'lote'), ''), 'S/L') lote,
           coalesce(nullif(btrim(f->>'fecha_vencimiento_cl'), ''), 'S/F') vencimiento,
           coalesce((f->>'cantidad_unidades')::numeric, 0)::int unidades
      from wms_despacho_lpn l, jsonb_array_elements(coalesce(l.descontado, l.filas)) f
     where l.despacho_id = p_id
  ),
  emp as (select s.sku, e.* from (select distinct sku from filas union select upper(sku) from wms_despacho_pedido where despacho_id = p_id) s,
                 lateral public.wms_empaque_sku(s.sku) e),
  por_lote as (
    select f.sku, f.lote, f.vencimiento, sum(f.unidades)::int unidades, count(distinct f.lpn)::int pallets,
           string_agg(distinct f.lpn, ', ') lpns
      from filas f group by 1, 2, 3
  ),
  por_sku as (
    select f.sku, sum(f.unidades)::int unidades, count(distinct f.lpn)::int pallets
      from filas f group by 1
  ),
  skus as (select sku from por_sku union select upper(sku) from wms_despacho_pedido where despacho_id = p_id)
  select jsonb_build_object(
    'despacho', (select to_jsonb(d) from d),
    'sku', coalesce((
      select jsonb_agg(jsonb_build_object(
               'sku', s.sku,
               'descripcion', coalesce(p.descripcion, e.descripcion),
               'pedido_unidades', p.unidades, 'pedido_pallets', p.pallets,
               'en_pedido', p.sku is not null,
               'pallets', coalesce(x.pallets, 0), 'unidades', coalesce(x.unidades, 0),
               'multiplo_caja', e.multiplo_caja, 'multiplo_display', e.multiplo_display,
               'empaque', public.wms_empaque_desglose(coalesce(x.unidades, 0), e.multiplo_caja, e.multiplo_display),
               'peso_kg', round(coalesce(x.unidades, 0) * coalesce(e.peso_unidad_kg, 0), 2),
               'falta', greatest(0, coalesce(p.unidades, 0) - coalesce(x.unidades, 0)),
               'sobra', greatest(0, coalesce(x.unidades, 0) - coalesce(p.unidades, 0)),
               'lotes', coalesce((select jsonb_agg(jsonb_build_object(
                           'lote', pl.lote, 'vencimiento', pl.vencimiento, 'unidades', pl.unidades, 'pallets', pl.pallets,
                           'lpns', pl.lpns,
                           'empaque', public.wms_empaque_desglose(pl.unidades, e.multiplo_caja, e.multiplo_display))
                           order by pl.vencimiento, pl.lote)
                          from por_lote pl where pl.sku = s.sku), '[]'::jsonb))
             order by (p.sku is null), s.sku)
        from skus s
        left join wms_despacho_pedido p on p.despacho_id = p_id and upper(p.sku) = s.sku
        left join por_sku x on x.sku = s.sku
        left join emp e on e.sku = s.sku), '[]'::jsonb),
    'lpns', coalesce((
      select jsonb_agg(jsonb_build_object(
               'lpn', l.lpn, 'ubicacion', l.ubicacion, 'escaneado_por', l.escaneado_por, 'escaneado_en', l.escaneado_en,
               'descontado', l.descontado is not null,
               'unidades', (select coalesce(sum((f->>'cantidad_unidades')::numeric), 0)::int
                              from jsonb_array_elements(coalesce(l.descontado, l.filas)) f),
               'contenido', (select jsonb_agg(jsonb_build_object(
                                'sku', upper(f->>'sku'), 'lote', coalesce(nullif(f->>'lote', ''), 'S/L'),
                                'vencimiento', coalesce(nullif(f->>'fecha_vencimiento_cl', ''), 'S/F'),
                                'unidades', (f->>'cantidad_unidades')::numeric::int,
                                'empaque', public.wms_empaque_desglose((f->>'cantidad_unidades')::numeric::int,
                                                                       e.multiplo_caja, e.multiplo_display)))
                              from jsonb_array_elements(coalesce(l.descontado, l.filas)) f
                              left join emp e on e.sku = upper(btrim(f->>'sku'))))
             order by l.escaneado_en desc)
        from wms_despacho_lpn l where l.despacho_id = p_id), '[]'::jsonb),
    'totales', jsonb_build_object(
      'pallets', (select count(*) from wms_despacho_lpn where despacho_id = p_id),
      'unidades', (select coalesce(sum(unidades), 0) from filas),
      'pedido_unidades', (select coalesce(sum(unidades), 0) from wms_despacho_pedido where despacho_id = p_id),
      'pedido_pallets', (select sum(pallets) from wms_despacho_pedido where despacho_id = p_id),
      'cajas', (select coalesce(sum((public.wms_empaque_desglose(x.unidades, e.multiplo_caja, e.multiplo_display)->>'cajas')::int), 0)
                  from por_sku x join emp e on e.sku = x.sku),
      'displays', (select coalesce(sum((public.wms_empaque_desglose(x.unidades, e.multiplo_caja, e.multiplo_display)->>'displays')::int), 0)
                     from por_sku x join emp e on e.sku = x.sku),
      'peso_kg', (select round(coalesce(sum(x.unidades * coalesce(e.peso_unidad_kg, 0)), 0), 1)
                    from por_sku x join emp e on e.sku = x.sku))
  );
$$;

create or replace function public.wms_despachos_lista(p_bodega text, p_dias integer default 60)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(to_jsonb(d) || jsonb_build_object(
           'pallets', (select count(*) from wms_despacho_lpn l where l.despacho_id = d.id),
           'unidades', (select coalesce(sum((f->>'cantidad_unidades')::numeric), 0)::int
                          from wms_despacho_lpn l, jsonb_array_elements(coalesce(l.descontado, l.filas)) f where l.despacho_id = d.id),
           'pedido_unidades', (select coalesce(sum(p.unidades), 0) from wms_despacho_pedido p where p.despacho_id = d.id),
           'skus_pedido', (select count(*) from wms_despacho_pedido p where p.despacho_id = d.id))
         order by (d.estado = 'ABIERTO') desc, d.id desc), '[]'::jsonb)
    from wms_despachos d
   where d.bodega = public.wms_bodega_valida(p_bodega)
     and (d.estado = 'ABIERTO' or d.creado_en >= now() - make_interval(days => greatest(1, coalesce(p_dias, 60))));
$$;

-- ---------------------------------------------------------------------
-- Acciones
-- ---------------------------------------------------------------------
create or replace function public.wms_despacho_crear(p_bodega text, p_destino text, p_referencia text,
                                                     p_contenedor text default null, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_id bigint;
  v_usuario text := public.wms_usuario_despacho(p_usuario);
begin
  insert into wms_despachos (numero, bodega, destino, referencia, contenedor, creado_por)
  values ('EXP-' || to_char(now() at time zone 'America/Santiago', 'YYMMDD-HH24MISS'),
          public.wms_bodega_valida(p_bodega), coalesce(nullif(upper(btrim(p_destino)), ''), 'PERÚ'),
          nullif(btrim(p_referencia), ''), nullif(upper(btrim(p_contenedor)), ''), v_usuario)
  returning id into v_id;
  return public.wms_despacho_detalle(v_id);
end $$;

-- p_lineas: [{sku, descripcion, unidades, pallets}] (reemplaza el pedido)
create or replace function public.wms_despacho_pedido_cargar(p_id bigint, p_lineas jsonb, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.wms_usuario_despacho(p_usuario);
  if not exists (select 1 from wms_despachos where id = p_id and estado = 'ABIERTO') then
    raise exception 'WMS: el despacho no está abierto';
  end if;
  delete from wms_despacho_pedido where despacho_id = p_id;
  insert into wms_despacho_pedido (despacho_id, sku, descripcion, unidades, pallets)
  select p_id, upper(btrim(x->>'sku')), max(x->>'descripcion'),
         sum(coalesce(nullif(x->>'unidades', '')::numeric, 0))::int, sum(nullif(x->>'pallets', '')::numeric)
    from jsonb_array_elements(coalesce(p_lineas, '[]'::jsonb)) x
   where nullif(btrim(x->>'sku'), '') is not null
   group by upper(btrim(x->>'sku'))
  having sum(coalesce(nullif(x->>'unidades', '')::numeric, 0)) > 0;
  return public.wms_despacho_detalle(p_id);
end $$;

create or replace function public.wms_despacho_editar(p_id bigint, p_destino text, p_referencia text,
                                                      p_contenedor text, p_nota text, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.wms_usuario_despacho(p_usuario);
  update wms_despachos
     set destino = coalesce(nullif(upper(btrim(p_destino)), ''), destino),
         referencia = coalesce(nullif(btrim(p_referencia), ''), referencia),
         contenedor = nullif(upper(btrim(coalesce(p_contenedor, contenedor))), ''),
         nota = nullif(btrim(coalesce(p_nota, nota)), '')
   where id = p_id and estado <> 'ANULADO';
  return public.wms_despacho_detalle(p_id);
end $$;

-- Escanear un LPN: lee su contenido del stock y lo suma al despacho
create or replace function public.wms_despacho_escanear(p_id bigint, p_lpn text, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_usuario text := public.wms_usuario_despacho(p_usuario);
  v_d wms_despachos;
  v_lpn text := upper(btrim(coalesce(p_lpn, '')));
  v_filas jsonb;
  v_ubic text;
  v_otro text;
  v_avisos text[] := '{}';
  v_sku record;
begin
  select * into v_d from wms_despachos where id = p_id for update;
  if v_d.id is null then raise exception 'WMS: el despacho no existe'; end if;
  if v_d.estado <> 'ABIERTO' then raise exception 'WMS: el despacho % está %', v_d.numero, v_d.estado; end if;
  if v_lpn ~ '^\d{18}$' then v_lpn := 'SSCC-' || v_lpn; end if;
  if v_lpn = '' then raise exception 'WMS: escanee el LPN'; end if;

  if exists (select 1 from wms_despacho_lpn where despacho_id = p_id and lpn = v_lpn) then
    return jsonb_build_object('resultado', 'YA_ESTABA', 'lpn', v_lpn, 'detalle', public.wms_despacho_detalle(p_id));
  end if;
  select d.numero into v_otro
    from wms_despacho_lpn l join wms_despachos d on d.id = l.despacho_id
   where l.lpn = v_lpn and d.estado = 'ABIERTO' and d.id <> p_id limit 1;
  if v_otro is not null then raise exception 'WMS: el LPN % ya está en el despacho %', v_lpn, v_otro; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id', i.id, 'sku', upper(btrim(i.sku)), 'lote', i.lote, 'fecha_vencimiento_cl', i.fecha_vencimiento_cl,
           'cantidad_unidades', i.cantidad_unidades, 'cajas', i.cajas, 'codigo_ubicacion', i.codigo_ubicacion) order by i.sku, i.lote), '[]'::jsonb),
         string_agg(distinct i.codigo_ubicacion, ', ')
    into v_filas, v_ubic
    from bodega_inventario_ubicacion i
   where i.bodega = v_d.bodega and upper(btrim(i.lpn)) = v_lpn and coalesce(i.cantidad_unidades, 0) > 0;
  if jsonb_array_length(v_filas) = 0 then
    raise exception 'WMS: el LPN % no tiene stock en % (¿está en el andén sin ubicar o ya salió?)', v_lpn, v_d.bodega;
  end if;

  insert into wms_despacho_lpn (despacho_id, lpn, ubicacion, filas, escaneado_por)
  values (p_id, v_lpn, v_ubic, v_filas, v_usuario);

  -- avisos: SKU fuera del pedido o que pasa lo pedido
  if exists (select 1 from wms_despacho_pedido where despacho_id = p_id) then
    for v_sku in
      select upper(f->>'sku') sku from jsonb_array_elements(v_filas) f group by 1
    loop
      if not exists (select 1 from wms_despacho_pedido where despacho_id = p_id and upper(sku) = v_sku.sku) then
        v_avisos := v_avisos || format('%s no está en el pedido', v_sku.sku);
      elsif (select coalesce(sum((f->>'cantidad_unidades')::numeric), 0)
               from wms_despacho_lpn l, jsonb_array_elements(l.filas) f
              where l.despacho_id = p_id and upper(f->>'sku') = v_sku.sku)
            > (select unidades from wms_despacho_pedido where despacho_id = p_id and upper(sku) = v_sku.sku) then
        v_avisos := v_avisos || format('%s pasa lo pedido', v_sku.sku);
      end if;
    end loop;
  end if;

  return jsonb_build_object('resultado', 'AGREGADO', 'lpn', v_lpn, 'ubicacion', v_ubic, 'avisos', to_jsonb(v_avisos),
                            'detalle', public.wms_despacho_detalle(p_id));
end $$;

create or replace function public.wms_despacho_quitar_lpn(p_id bigint, p_lpn text, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.wms_usuario_despacho(p_usuario);
  if not exists (select 1 from wms_despachos where id = p_id and estado = 'ABIERTO') then
    raise exception 'WMS: el despacho no está abierto';
  end if;
  delete from wms_despacho_lpn where despacho_id = p_id and lpn = upper(btrim(p_lpn));
  return public.wms_despacho_detalle(p_id);
end $$;

-- Cerrar: si p_descontar, cada LPN sale del stock (kardex DESPACHO_EXPORTACION)
create or replace function public.wms_despacho_cerrar(p_id bigint, p_descontar boolean, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_usuario text := public.wms_usuario_despacho(p_usuario);
  v_d wms_despachos;
  l record;
  r record;
  v_filas jsonb;
  v_n int := 0;
  v_un int := 0;
begin
  select * into v_d from wms_despachos where id = p_id for update;
  if v_d.id is null or v_d.estado <> 'ABIERTO' then raise exception 'WMS: el despacho no está abierto'; end if;
  if not exists (select 1 from wms_despacho_lpn where despacho_id = p_id) then
    raise exception 'WMS: el despacho no tiene LPN escaneados';
  end if;

  if coalesce(p_descontar, false) then
    for l in select * from wms_despacho_lpn where despacho_id = p_id loop
      perform pg_advisory_xact_lock(hashtext('LPN|' || l.lpn));
      select coalesce(jsonb_agg(jsonb_build_object(
               'id', i.id, 'sku', upper(btrim(i.sku)), 'lote', i.lote, 'fecha_vencimiento_cl', i.fecha_vencimiento_cl,
               'cantidad_unidades', i.cantidad_unidades, 'cajas', i.cajas, 'codigo_ubicacion', i.codigo_ubicacion)), '[]'::jsonb)
        into v_filas
        from bodega_inventario_ubicacion i
       where i.bodega = v_d.bodega and upper(btrim(i.lpn)) = l.lpn and coalesce(i.cantidad_unidades, 0) > 0;
      for r in select * from bodega_inventario_ubicacion i
                where i.bodega = v_d.bodega and upper(btrim(i.lpn)) = l.lpn and coalesce(i.cantidad_unidades, 0) > 0 loop
        perform public.wms_kardex(v_d.bodega, 'DESPACHO_EXPORTACION', l.lpn, r.sku, r.lote, r.codigo_ubicacion,
                                  left(v_d.numero || ' ' || v_d.destino, 60), -coalesce(r.cajas, 0), -coalesce(r.cantidad_unidades, 0));
        v_un := v_un + coalesce(r.cantidad_unidades, 0);
      end loop;
      delete from bodega_inventario_ubicacion i
       where i.bodega = v_d.bodega and upper(btrim(i.lpn)) = l.lpn and coalesce(i.cantidad_unidades, 0) > 0;
      update wms_despacho_lpn set descontado = v_filas where id = l.id;
      v_n := v_n + 1;
    end loop;
  end if;

  update wms_despachos
     set estado = 'CERRADO', stock_descontado = coalesce(p_descontar, false), cerrado_por = v_usuario, cerrado_en = now()
   where id = p_id;
  return jsonb_build_object('numero', v_d.numero, 'lpn_descontados', v_n, 'unidades_descontadas', v_un,
                            'detalle', public.wms_despacho_detalle(p_id));
end $$;

-- Descontar el stock de un despacho ya cerrado sin descontar
create or replace function public.wms_despacho_descontar(p_id bigint, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from wms_despachos where id = p_id and estado = 'CERRADO' and not stock_descontado) then
    raise exception 'WMS: el despacho no está cerrado o ya se descontó';
  end if;
  update wms_despachos set estado = 'ABIERTO' where id = p_id;
  return public.wms_despacho_cerrar(p_id, true, p_usuario);
end $$;

create or replace function public.wms_despacho_reabrir(p_id bigint, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.wms_usuario_despacho(p_usuario);
  if not exists (select 1 from wms_despachos where id = p_id and estado = 'CERRADO' and not stock_descontado) then
    raise exception 'WMS: solo se puede reabrir un despacho cerrado que no descontó stock';
  end if;
  update wms_despachos set estado = 'ABIERTO', cerrado_por = null, cerrado_en = null where id = p_id;
  return public.wms_despacho_detalle(p_id);
end $$;

create or replace function public.wms_despacho_anular(p_id bigint, p_usuario text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.wms_usuario_despacho(p_usuario);
  if exists (select 1 from wms_despachos where id = p_id and stock_descontado) then
    raise exception 'WMS: el despacho ya descontó stock; no se puede anular';
  end if;
  update wms_despachos set estado = 'ANULADO', cerrado_por = public.wms_usuario_despacho(p_usuario), cerrado_en = now()
   where id = p_id;
  return public.wms_despacho_detalle(p_id);
end $$;

